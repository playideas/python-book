import 페테크 as ft
import 가상팔

시계, 가짜, 버스 = 가상팔.만들기()

# 1) ID 찾기: 1번부터 12번까지 핑을 보내 답하는 서보를 찾는다
찾은 = [i for i in range(1, 13) if 버스.핑(i)]
print("답한 ID:", 찾은)
print("모델 번호:", {i: 버스.읽기(i, ft.모델번호) for i in 찾은})

# 2) 보정하고, 서보에 적힌 값을 다시 읽어 확인한다
가상팔.보정하기(버스, 가짜)
print(f"{'관절':14s} ID  영점보정  최소  최대  지금(도)")
지금 = 가상팔.눈금_각도(버스.함께_읽기(ft.현재_위치, 가상팔.아이디들))
for j, (이름, i) in enumerate(zip(가상팔.관절들, 가상팔.아이디들)):
    영점, 최소, 최대 = (버스.읽기(i, r) for r in (ft.영점_보정, ft.최소_위치, ft.최대_위치))
    print(f"{이름:14s} {i:2d} {영점:8d} {최소:5d} {최대:5d} {지금[j]:8.1f}")
