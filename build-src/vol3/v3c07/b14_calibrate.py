import 페테크 as ft
from 가짜서보 import 가상시계, 가짜버스, 가짜서보
from 서보통신 import 서보버스

# 이 관절은 한가운데에 있을 때 서보 축이 우연히 3100눈금에 놓이도록 조립됐다
관절_가운데_실제 = 3100
시계 = 가상시계()
서보 = 가짜서보(1, 실제_위치=2600)
가짜 = 가짜버스([서보], 시계)
버스 = 서보버스(가짜.포트_이름, 속도=115_200)

# 1) 토크를 끄고, 사람이 관절을 한가운데에 둔다
버스.쓰기(1, ft.토크_켜기, 0)
서보.손으로_돌리기(관절_가운데_실제)
읽은 = 버스.읽기(1, ft.현재_위치)
영점 = 읽은 - 2047                              # 이만큼 빼면 한가운데가 2047이 된다
버스.쓰기(1, ft.영점_보정, 영점)
print(f"한가운데에서 읽은 값 {읽은} → 영점 보정 {영점} → 다시 읽으면 {버스.읽기(1, ft.현재_위치)}")

# 2) 사람이 관절을 양 끝까지 돌리는 동안 읽은 값의 최소·최대를 기록한다
기록 = []
for 실제 in range(관절_가운데_실제 - 1100, 관절_가운데_실제 + 1201, 100):
    서보.손으로_돌리기(실제)
    기록.append(버스.읽기(1, ft.현재_위치))
최소, 최대 = min(기록), max(기록)
버스.쓰기(1, ft.최소_위치, 최소)
버스.쓰기(1, ft.최대_위치, 최대)
print(f"움직인 범위: {최소} ~ {최대}")

# 3) 한계 밖의 목표를 보내면?
버스.쓰기(1, ft.목표_위치, 버스.읽기(1, ft.현재_위치))
버스.쓰기(1, ft.토크_켜기, 1)
버스.쓰기(1, ft.목표_위치, 4000)
시계.진행(1.0)
print("목표 4000을 보냈더니 멈춘 곳:", 버스.읽기(1, ft.현재_위치))

음수_영점 = ft.명령_패킷(1, ft.WRITE, bytes([31]) + ft.값_바이트(ft.영점_보정, -300))
print("영점 보정 -300을 쓰는 패킷:", 음수_영점.hex(" "))
