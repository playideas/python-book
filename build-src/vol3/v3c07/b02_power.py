# 전력(W) = 전압(V) × 전류(A)
전압 = 5.0                         # 서보 전원 어댑터의 전압(V)

# 아래 전류 값은 계산 연습용 예시다. 실제 값은 서보의 데이터시트에서 확인한다
평소_전류 = 0.15                   # 서보 하나가 가볍게 움직일 때(A)
정지_전류 = 2.0                    # 서보 하나가 꽉 막혀 버틸 때(stall, A)
서보_수 = 6

print(f"평소: {서보_수 * 평소_전류:.1f}A, {전압 * 서보_수 * 평소_전류:.1f}W")
print(f"모두 막혔을 때: {서보_수 * 정지_전류:.1f}A, {전압 * 서보_수 * 정지_전류:.0f}W")

for 어댑터_전류 in [2.0, 4.0, 10.0]:
    버티는_서보 = int(어댑터_전류 // 정지_전류)
    print(f"{어댑터_전류:4.1f}A 어댑터: 동시에 막혀도 버티는 서보 {버티는_서보}개")

# 배터리로 돌리면 얼마나 갈까: 용량(mAh) ÷ 평균 전류(mA)
용량_mAh = 2200
평균_전류_mA = 1500                 # 팔이 쉬지 않고 움직일 때의 평균이라고 치자
print(f"{용량_mAh}mAh 배터리: 약 {용량_mAh / 평균_전류_mA * 60:.0f}분")
