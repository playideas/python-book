import numpy as np

눈금_각도_도 = 360 / 4096
팔_길이 = 0.25                   # 어깨에서 손끝까지(m, 예시)

# 보정을 대충 해서 영점이 몇 눈금 어긋났다면, 손끝은 얼마나 빗나갈까
for 어긋난_눈금 in [1, 10, 50]:
    각도_오차 = np.deg2rad(어긋난_눈금 * 눈금_각도_도)
    print(f"영점 {어긋난_눈금:2d}눈금 어긋남 = {np.rad2deg(각도_오차):.2f}도 → "
          f"손끝 약 {팔_길이 * 각도_오차 * 1000:.1f}mm 빗나감")
