import 페테크 as ft
from 가짜서보 import 가상시계, 가짜버스, 가짜서보
from 서보통신 import 서보버스

시계 = 가상시계()
가짜 = 가짜버스([가짜서보(1, 실제_위치=1500)], 시계)    # 실물이라면 USB에 꽂은 서보 한 개
버스 = 서보버스(가짜.포트_이름, 속도=115_200)           # 실물이라면 '/dev/ttyACM0' 같은 이름

print("ID 1 핑:", 버스.핑(1), "/ ID 2 핑:", 버스.핑(2))
print("모델 번호:", 버스.읽기(1, ft.모델번호))
print("현재 위치:", 버스.읽기(1, ft.현재_위치))

버스.쓰기(1, ft.목표_위치, 2500)
시계.진행(0.2)
print("토크가 꺼진 채 목표 2500을 주고 0.2초 뒤:", 버스.읽기(1, ft.현재_위치))

버스.쓰기(1, ft.목표_위치, 버스.읽기(1, ft.현재_위치))  # 켜기 전에 목표를 지금 위치로 맞춘다
버스.쓰기(1, ft.토크_켜기, 1)
버스.쓰기(1, ft.목표_위치, 2500)
for 단계 in range(1, 6):
    시계.진행(0.1)
    print(f"  토크를 켜고 {단계 * 0.1:.1f}초: {버스.읽기(1, ft.현재_위치)}")
