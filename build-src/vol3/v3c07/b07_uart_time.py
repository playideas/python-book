# UART는 바이트 하나를 보낼 때 시작 비트 1 + 데이터 8 + 정지 비트 1 = 10비트를 쓴다
비트_per_바이트 = 10
서보_수 = 6


def 전송_시간_us(바이트_수: int, 보드레이트: int) -> float:
    return 바이트_수 * 비트_per_바이트 / 보드레이트 * 1e6


# 한 주기에 '서보 6개에 목표 쓰기 + 현재 위치 읽기'를 하는 두 가지 방법(바이트 수)
따로따로 = 서보_수 * (9 + 6) + 서보_수 * (8 + 8)     # WRITE와 응답, READ와 응답을 서보마다
함께 = (7 + 서보_수 * 3 + 1) + (7 + 서보_수 + 1) + 서보_수 * 8   # SYNC_WRITE 하나, SYNC_READ와 응답 6개

for 보드레이트 in [115_200, 1_000_000]:
    print(f"{보드레이트:>9,}bps: 바이트 하나 {전송_시간_us(1, 보드레이트):5.1f}μs")
    for 이름, 바이트 in [("따로따로", 따로따로), ("함께", 함께)]:
        시간 = 전송_시간_us(바이트, 보드레이트)
        print(f"   {이름:4s} {바이트:3d}바이트 = {시간 / 1000:5.2f}ms → 선만 보면 최대 {1e6 / 시간:5.0f}Hz")
