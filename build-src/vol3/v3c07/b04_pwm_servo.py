# 취미용 서보에 흔한 약속(제품마다 다르니 데이터시트로 확인한다):
# 20ms(50Hz)마다 펄스 하나, 폭 1.0ms = 0도, 1.5ms = 90도, 2.0ms = 180도
주기_ms = 20.0
최소_폭_ms, 최대_폭_ms, 각도_범위_도 = 1.0, 2.0, 180.0


def 펄스_폭(각도_도: float) -> float:
    """각도를 펄스 폭(ms)으로."""
    return 최소_폭_ms + (최대_폭_ms - 최소_폭_ms) * 각도_도 / 각도_범위_도


for 각도 in [0, 45, 90, 180]:
    폭 = 펄스_폭(각도)
    print(f"{각도:3d}도 → 펄스 {폭:.3f}ms, 듀티 {폭 / 주기_ms:.1%}")

# 마이크로컨트롤러의 타이머가 1μs 단위로 폭을 조절한다면 각도 해상도는?
print(f"1μs 차이 = {각도_범위_도 / ((최대_폭_ms - 최소_폭_ms) * 1000):.2f}도")
