import numpy as np

# DC 모터 + 모터 드라이버: 12V를 아주 빠르게 켰다 껐다 하며 '켜진 비율(듀티)'로 세기를 정한다
전원 = 12.0                     # V
PWM_주파수 = 20_000             # Hz. 사람 귀에 들리지 않게 20kHz로 흔히 고른다
속도_상수 = 25.0                # 1V에 25rad/s(예시)
시간_상수 = 0.05                # 1장 1.3절의 DC 모터와 같은 0.05초
간격 = 1 / PWM_주파수 / 20      # 펄스 하나를 20조각으로 나눠 흉내

for 듀티 in [0.25, 0.5, 0.75]:
    속도, 기록 = 0.0, []
    for k in range(round(0.3 / 간격)):          # 0.3초 동안
        켜짐 = (k % 20) < 듀티 * 20              # 한 펄스 안에서 켜진 조각인가
        전압 = 전원 if 켜짐 else 0.0
        속도 += (속도_상수 * 전압 - 속도) * 간격 / 시간_상수
        기록.append(속도)
    끝 = np.array(기록[-2000:])                  # 마지막 0.005초
    print(f"듀티 {듀티:.0%}: 평균 전압 {듀티 * 전원:4.1f}V → 속도 {끝.mean():6.1f}rad/s "
          f"(흔들림 {np.ptp(끝):.2f}rad/s)")
