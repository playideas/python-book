# 옴의 법칙: 전선에 걸리는 전압 = 전류 × 전선의 저항
어댑터_전압 = 5.0
전선_저항 = 0.1                    # 가늘고 긴 전선 왕복의 저항(Ω, 예시)
컴퓨터_최저_전압 = 4.75             # 이보다 낮으면 컴퓨터가 꺼졌다 켜진다고 치자(예시)

for 전류 in [0.5, 2.0, 6.0, 12.0]:
    남은_전압 = 어댑터_전압 - 전류 * 전선_저항
    상태 = "[O]" if 남은_전압 >= 컴퓨터_최저_전압 else "[X] 컴퓨터 재부팅"
    print(f"전류 {전류:4.1f}A → 끝에 남는 전압 {남은_전압:.2f}V {상태}")
