import 페테크 as ft
from 가짜서보 import 가상시계, 가짜버스, 가짜서보
from 서보통신 import 서보버스, 통신실패

# 응답의 10%가 사라지고 5%는 비트 하나가 깨지는 나쁜 선
for 재시도 in [0, 1, 2]:
    가짜 = 가짜버스([가짜서보(1)], 가상시계(), 손실률=0.10, 깨짐률=0.05, 씨앗=1)
    버스 = 서보버스(가짜.포트_이름, 속도=115_200, 재시도=재시도)
    실패 = 0
    for _ in range(1000):
        try:
            버스.읽기(1, ft.현재_위치)
        except 통신실패:
            실패 += 1
    print(f"재시도 {재시도}번: 1000번 중 실패 {실패:3d}번 "
          f"(시간 초과 {버스.통계['시간 초과']}, 체크섬 오류 {버스.통계['체크섬 오류']})")
