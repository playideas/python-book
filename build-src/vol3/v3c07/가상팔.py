"""7.12절 실습: SO-101 팔로워 팔의 서보 6개를 흉내 낸 가상 버스와 보정·변환 도구."""
import numpy as np

import 페테크 as ft
from 가짜서보 import 가상시계, 가짜버스, 가짜서보
from 서보통신 import 서보버스

관절들 = ["shoulder_pan", "shoulder_lift", "elbow_flex", "wrist_flex", "wrist_roll", "gripper"]
아이디들 = [1, 2, 3, 4, 5, 6]                    # LeRobot의 SO-101과 같은 번호
방향들 = [1, -1, 1, 1, 1, 1]                      # 연습용으로 2번 서보를 반대로 달았다고 치자
도_눈금 = 4096 / 360
쉬는_자세 = [0, -95, 90, 70, 0, 0]               # 전원을 켰을 때 팔이 놓인 자세(도)

# 실물에서는 모르는 값: 관절이 한가운데일 때 서보 축의 실제 눈금, 관절이 움직이는 범위(도)
_조립_가운데 = [1980, 2210, 1830, 2105, 2048, 2390]
_관절_범위 = [110, 100, 95, 100, 180, 50]


def _실제_눈금(j: int, 각도_도: float) -> float:
    return _조립_가운데[j] + 방향들[j] * 각도_도 * 도_눈금


def 만들기(**오류) -> tuple[가상시계, 가짜버스, 서보버스]:
    """전원을 켠 직후의 가상 팔과 그 팔에 연결된 서보버스."""
    시계 = 가상시계()
    서보들 = [가짜서보(i, 실제_위치=_실제_눈금(j, 쉬는_자세[j])) for j, i in enumerate(아이디들)]
    가짜 = 가짜버스(서보들, 시계, **오류)
    return 시계, 가짜, 서보버스(가짜.포트_이름, 속도=115_200)


def 참_각도(가짜: 가짜버스) -> np.ndarray:
    """가짜 팔만 아는 진짜 관절 각도(도). 검산용."""
    return np.array([(가짜.서보들[i].실제_위치 - _조립_가운데[j]) * 방향들[j] / 도_눈금
                     for j, i in enumerate(아이디들)])


def 손으로_두기(가짜: 가짜버스, 각도들_도: list[float]) -> None:
    for j, i in enumerate(아이디들):
        가짜.서보들[i].손으로_돌리기(_실제_눈금(j, 각도들_도[j]))


def 보정하기(버스: 서보버스, 가짜: 가짜버스) -> None:
    """LeRobot과 같은 순서의 보정. 사람이 관절을 옮기는 일은 손으로_두기로 흉내 낸다."""
    for i in 아이디들:
        버스.쓰기(i, ft.토크_켜기, 0)
        버스.쓰기(i, ft.영점_보정, 0)
    손으로_두기(가짜, [0] * 6)                       # 1) 모든 관절을 한가운데에
    for i, 읽음 in 버스.함께_읽기(ft.현재_위치, 아이디들).items():
        버스.쓰기(i, ft.영점_보정, 읽음 - 2047)
    최소, 최대 = {i: 4095 for i in 아이디들}, {i: 0 for i in 아이디들}
    for 비율 in np.linspace(-1, 1, 21):              # 2) 관절을 끝에서 끝까지 돌려 본다
        손으로_두기(가짜, [비율 * 범위 for 범위 in _관절_범위])
        for i, 읽음 in 버스.함께_읽기(ft.현재_위치, 아이디들).items():
            최소[i], 최대[i] = min(최소[i], 읽음), max(최대[i], 읽음)
    최소[5], 최대[5] = 0, 4095                       # wrist_roll은 한 바퀴를 다 쓴다
    for i in 아이디들:                               # 3) 범위를 서보에 적는다
        버스.쓰기(i, ft.최소_위치, 최소[i])
        버스.쓰기(i, ft.최대_위치, 최대[i])
    손으로_두기(가짜, 쉬는_자세)                      # 보정을 마치고 팔을 내려놓는다


def 각도_눈금(각도들_도: np.ndarray) -> dict[int, int]:
    return {i: round(2047 + 방향들[j] * 각도들_도[j] * 도_눈금) for j, i in enumerate(아이디들)}


def 눈금_각도(읽음: dict[int, int]) -> np.ndarray:
    return np.array([방향들[j] * (읽음[i] - 2047) / 도_눈금 for j, i in enumerate(아이디들)])
