import numpy as np

from 안전감싸개 import 안전감싸개
from 팔제어 import 목표들, 제어기_만들기
from 현실팔 import 시뮬_물성, 실행, 주기, 현실_물성

범위 = np.deg2rad([[-100, 60], [-90, 90]])           # 어깨, 팔꿈치가 다녀도 되는 각도(도 → rad)
부호 = np.array([1.0, -1.0])                          # 실수: 팔꿈치 모터의 방향을 반대로 조립했다


def 천천히(최대_속도: float = 0.5):
    """첫 목표 자세로 한 주기에 최대_속도(rad/s) × 주기씩만 다가가는 목표."""
    지금 = np.array([-np.pi / 2, 0.0])

    def 목표값(t: float) -> np.ndarray:
        nonlocal 지금
        지금 = 지금 + np.clip(목표들[0] - 지금, -최대_속도 * 주기, 최대_속도 * 주기)
        return 지금
    return 목표값


def 뒤집힌_팔꿈치(제어기):
    return lambda t, 잰_각도: 제어기(t, 잰_각도) * 부호


for 이름 in ["감싸개 없이", "안전감싸개", "방향을 고침 + 안전감싸개", "방향을 고침 + 안전감싸개 + 천천히"]:
    제어기 = 제어기_만들기(40, 4, 시뮬_물성, 천천히() if 이름.endswith("천천히") else lambda t: 목표들[0])
    if not 이름.startswith("방향을 고침"):
        제어기 = 뒤집힌_팔꿈치(제어기)
    if 이름 != "감싸개 없이":
        제어기 = 안전감싸개(제어기, 범위)
    기록 = 실행(제어기, 4.0, 현실_물성)       # 첫 목표(-30, 60도) 하나만 4초 동안
    팔꿈치_도 = np.rad2deg(기록["참_각도"][:, 1])
    속도 = np.abs(기록["잰_각도"][5:, 1] - 기록["잰_각도"][:-5, 1]) / (5 * 주기)    # 감싸개처럼 0.05초 사이로
    print(f"{이름}: 팔꿈치 각도 {팔꿈치_도.min():7.1f} ~ {팔꿈치_도.max():6.1f}도, 가장 빠를 때 {속도.max():5.1f}rad/s, "
          f"가장 센 토크 {np.abs(기록['토크'][:, 1]).max():.1f}N·m")
    if 이름 != "감싸개 없이":
        print("  " + (f"{제어기.멈춘_시각:.2f}초에 멈춤, 까닭: {제어기.멈춘_까닭}" if 제어기.멈춘_시각 is not None
                      else f"멈추지 않음, 4초 뒤 오차 {np.round(np.rad2deg(목표들[0] - 기록['참_각도'][-1]), 2) + 0.0}도"))
