import numpy as np

from 팔제어 import 돌려_보기
from 현실팔 import 시뮬_물성, 현실_물성

kp들, kd들 = [20, 30, 40, 60, 80, 110], [1, 2, 3, 4, 6, 8]

# 12장 12.8절처럼 시뮬에서 이득 표를 훑어 가장 좋은 칸을 고른다
점수 = {(kp, kd): 돌려_보기(kp, kd, 시뮬_물성, 시뮬_물성)[0] for kp in kp들 for kd in kd들}
kp, kd = min(점수, key=점수.get)
print(f"시뮬에서 고른 이득: kp={kp}, kd={kd}")

시뮬_오차, 시뮬_못감 = 돌려_보기(kp, kd, 시뮬_물성, 시뮬_물성)
현실_오차, 현실_못감 = 돌려_보기(kp, kd, 시뮬_물성, 현실_물성)
print(f"시뮬에서: 평균 오차 {시뮬_오차:5.2f}도, 못 간 목표 {시뮬_못감}/4")
print(f"현실에서: 평균 오차 {현실_오차:5.2f}도, 못 간 목표 {현실_못감}/4")
