"""13장: ㄷ자 장면의 퍼텐셜 필드. 목표는 끌어당기고 벽은 밀어낸다."""
import numpy as np

from 디귿장면 import 목표, 벽까지

당김 = 1.0           # 목표가 당기는 세기
밂 = 0.02            # 벽이 미는 세기
밂_범위 = 0.4        # m. 벽에서 이보다 멀면 밀지 않는다(1장의 감지 범위)


def 퍼텐셜(위치: np.ndarray) -> float:
    """높이(에너지): 목표에서 멀수록, 벽에 가까울수록 높다."""
    U = 0.5 * 당김 * np.sum((위치 - 목표) ** 2)
    d, _ = 벽까지(위치)
    if d < 밂_범위:
        U += 0.5 * 밂 * (1 / max(d, 1e-3) - 1 / 밂_범위) ** 2
    return U


def 내리막(위치: np.ndarray) -> np.ndarray:
    """-∇U: 높이가 가장 빨리 낮아지는 방향과 세기."""
    힘 = 당김 * (목표 - 위치)
    d, 바깥 = 벽까지(위치)
    if d < 밂_범위:
        d = max(d, 1e-3)
        힘 = 힘 + 밂 * (1 / d - 1 / 밂_범위) / d**2 * 바깥
    return 힘
