import numpy as np

from 격자도구 import 해상도
from 격자탐색 import 경로_길이, 맨해튼, 옥타일, 탐색
from 지도준비 import 로봇_반지름, 막힌_칸, 부풀리기, 칸

통과 = 부풀리기(막힌_칸(), 로봇_반지름)
시작, 목표 = 칸((9.0, 7.2)), 칸((1.5, 0.4))           # 오른쪽 위 구석에서 왼쪽 아래 구석으로

# 목표까지 '진짜로' 남은 거리를 모든 칸에 대해 구해 두고, 휴리스틱과 견준다
남은, _ = 탐색(통과, 목표, None, "다익스트라")      # 목표에서 출발해 끝까지 펼친다
갈수있음 = np.isfinite(남은)
칸들 = np.argwhere(갈수있음)
for 이름, 휴리스틱 in [("옥타일", 옥타일), ("맨해튼", 맨해튼)]:
    h = np.array([휴리스틱(tuple(c), 목표) for c in 칸들])
    넘침 = h > 남은[갈수있음] + 1e-9
    print(f"{이름}: 갈 수 있는 {len(칸들)}칸 중 진짜 남은 거리보다 크게 어림한 칸 {넘침.sum()}개"
          f" (가장 크게 넘친 것 {(h - 남은[갈수있음]).max() * 해상도:.3f}m)")

print("가장 짧은 경로 길이:", round(float(남은[시작] * 해상도), 3), "m")
for 이름, 휴리스틱, 가중치 in [("A* 옥타일", 옥타일, 1.0), ("A* 맨해튼", 맨해튼, 1.0), ("가중 A* 옥타일×2", 옥타일, 2.0)]:
    경로, 펼침 = 탐색(통과, 시작, 목표, "A*", 휴리스틱, 가중치)
    print(f"{이름}: 경로 {경로_길이(경로, 해상도):.3f}m, 펼친 칸 {펼침.sum()}")
