import numpy as np

from 디귿장면 import 목표, 규칙_달리기, 벽까지

경로 = 규칙_달리기(걸음_수=600)                     # 60초 동안 달리기
벽과_가장_가까이 = min(벽까지(p)[0] for p in 경로)
print(f"60초 뒤 위치 {np.round(경로[-1], 3)}, 목표까지 {np.linalg.norm(목표 - 경로[-1]):.3f}m")
print(f"벽과 가장 가까울 때 {벽과_가장_가까이:.3f}m")
마지막_10초 = 경로[-100:]
print(f"마지막 10초 동안 움직인 범위: x {np.ptp(마지막_10초[:, 0]):.3f}m, y {np.ptp(마지막_10초[:, 1]):.3f}m")
