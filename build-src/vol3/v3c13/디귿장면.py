"""13장: ㄷ자 벽이 길을 막은 평면과, 1장의 규칙 세 개로 달리는 점 로봇."""
import numpy as np

from 점로봇 import 속도_제한, 최대_속도, 움직이기

시작, 목표 = np.array([0.0, 1.0]), np.array([3.0, 1.0])
# 벽은 직사각형 (x최소, x최대, y최소, y최대). 입구가 시작점 쪽(왼쪽)으로 열린 ㄷ자
벽들 = np.array([[1.9, 2.0, 0.3, 1.7],      # 안쪽 벽(목표를 가로막는다)
                 [1.0, 2.0, 1.6, 1.7],      # 위 팔
                 [1.0, 2.0, 0.3, 0.4]])     # 아래 팔
감지_범위 = 0.4
주기, 이득 = 0.1, 1.5


def 벽까지(위치: np.ndarray) -> tuple[float, np.ndarray]:
    """가장 가까운 벽 표면까지의 거리와, 그 벽에서 로봇 쪽을 향한 단위 벡터."""
    가까운_점들 = np.stack([np.clip(위치[0], 벽들[:, 0], 벽들[:, 1]),
                        np.clip(위치[1], 벽들[:, 2], 벽들[:, 3])], axis=1)
    차이 = 위치 - 가까운_점들
    거리 = np.linalg.norm(차이, axis=1)
    i = int(np.argmin(거리))
    return float(거리[i]), 차이[i] / max(거리[i], 1e-9)


def 판단(위치: np.ndarray) -> np.ndarray:
    """1장 1.8절의 규칙 1~3: 목표 쪽으로, 벽에서 밀려나며, 벽 둘레를 따라 옆으로."""
    속도 = 속도_제한(이득 * (목표 - 위치))
    거리, 바깥 = 벽까지(위치)
    if 거리 > 감지_범위:
        return 속도
    세기 = 최대_속도 * 2 * (1 - 거리 / 감지_범위)
    둘레 = np.array([-바깥[1], 바깥[0]])
    if np.dot(둘레, 목표 - 위치) < 0:
        둘레 = -둘레
    return 속도 + 세기 * 바깥 + 세기 * 둘레


def 규칙_달리기(걸음_수: int = 600) -> np.ndarray:
    """규칙대로 걸음_수만큼(주기 0.1초) 달린 경로."""
    위치, 경로 = 시작.copy(), [시작.copy()]
    for _ in range(걸음_수):
        위치 = 움직이기(위치, 판단(위치), 주기)
        경로.append(위치)
    return np.array(경로)
