"""13장 실습: RRT → 지름길 → 시간 매기기를 한 줄로 잇는다."""
import numpy as np

from 시간매기기 import 멈추며_가는_궤적
from 실습장면 import 관절_한계, 목표_자세, 시작_자세, 충돌검사기
from 표본계획 import RRT, 경로_길이, 지름길

v최대, a최대 = 1.0, 2.0          # 관절마다 rad/s, rad/s²


def 계획하기(씨앗: int = 0, 여유: float = 0.03):
    """(계획 정보 사전, 걸리는 시간, 시각 → 자세 함수)를 돌려준다."""
    검사기 = 충돌검사기(여유)
    생성기 = np.random.default_rng(씨앗)
    날것, 나무, _, 반복 = RRT(시작_자세, 목표_자세, 검사기.선분_충돌, 관절_한계[:, 0], 관절_한계[:, 1],
                         생성기, 걸음=0.3, 최대_반복=8000)
    짧게 = 지름길(날것, 검사기.선분_충돌, 생성기)
    총시간, 자세 = 멈추며_가는_궤적(짧게, v최대, a최대)
    정보 = {"RRT 반복": 반복, "나무 점": len(나무), "RRT 꼭짓점": len(날것), "지름길 꼭짓점": len(짧게),
          "경로 길이(rad)": round(경로_길이(짧게), 3), "충돌 검사": 검사기.검사_수}
    return 정보, 총시간, 자세
