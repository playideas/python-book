"""11장: 로그 오즈로 갱신하는 점유 격자 지도."""
import numpy as np

from 포즈도구 import 점_옮기기, 포즈_행렬

해상도 = 0.05            # m. 칸 하나의 한 변
지도_원점 = (-0.5, -0.5)  # m. 격자 왼쪽 아래 모서리의 방 좌표
지도_크기 = (220, 180)    # 칸 수(x 방향, y 방향): 11m × 9m
찬칸_증거 = 0.85          # 레이가 끝난 칸에 더하는 로그 오즈(확률 0.7만큼의 증거)
빈칸_증거 = -0.4          # 레이가 지나간 칸에 더하는 로그 오즈(확률 0.4만큼의 증거)
로그오즈_한계 = 5.0       # 너무 확신하지 않도록 ±5에서 자른다


def 로그오즈(확률):
    return np.log(확률 / (1 - 확률))


def 확률로(로그오즈_값):
    return 1 - 1 / (1 + np.exp(로그오즈_값))


class 점유격자:
    def __init__(self) -> None:
        self.값 = np.zeros(지도_크기)         # 로그 오즈 0 = 확률 0.5 = 모름

    def 칸_번호(self, 점들: np.ndarray) -> np.ndarray:
        """방 기준 점들(N×2)이 들어 있는 칸의 번호(한 줄로 편 번호). 지도 밖 점은 뺀다."""
        i, j = np.floor((점들 - 지도_원점) / 해상도).astype(int).T
        안 = (i >= 0) & (i < 지도_크기[0]) & (j >= 0) & (j < 지도_크기[1])
        return np.ravel_multi_index((i[안], j[안]), 지도_크기)

    def 스캔_넣기(self, 포즈, 스캔: np.ndarray) -> None:
        """포즈에서 잰 스캔(로봇 기준 점들)으로 지나간 칸은 빈칸, 끝난 칸은 찬칸 쪽으로."""
        포즈 = np.asarray(포즈, dtype=float)
        끝점들 = 점_옮기기(포즈_행렬(포즈), 스캔)
        길이 = np.linalg.norm(스캔, axis=1)
        # 레이마다 칸 크기의 절반 간격으로 점을 찍어 지나간 칸을 찾는다(끝 칸 바로 앞까지)
        간격 = np.arange(0, 길이.max(), 해상도 / 2)
        비율 = 간격[None, :] / 길이[:, None]
        지나감 = 간격[None, :] < (길이[:, None] - 해상도)
        표본 = 포즈[:2] + 비율[..., None] * (끝점들 - 포즈[:2])[:, None, :]
        # 한 스캔에서 같은 칸은 한 번만 센다. 찬칸으로 끝난 칸은 빈칸에서 뺀다
        찬_칸 = np.unique(self.칸_번호(끝점들))
        빈_칸 = np.setdiff1d(self.칸_번호(표본[지나감]), 찬_칸)
        평평 = self.값.reshape(-1)                 # 같은 메모리를 1차원으로 보는 창
        평평[빈_칸] += 빈칸_증거
        평평[찬_칸] += 찬칸_증거
        np.clip(self.값, -로그오즈_한계, 로그오즈_한계, out=self.값)

    def 확률(self) -> np.ndarray:
        return 확률로(self.값)

    def 범위(self) -> list[float]:
        """imshow의 extent: 그림 축을 방 좌표(m)로 맞춘다."""
        x0, y0 = 지도_원점
        return [x0, x0 + 지도_크기[0] * 해상도, y0, y0 + 지도_크기[1] * 해상도]


def 지도_만들기(포즈들, 스캔들: list) -> 점유격자:
    """포즈마다 그때의 스캔을 넣어 지도 한 장을 만든다."""
    지도 = 점유격자()
    for 포즈, 스캔 in zip(포즈들, 스캔들):
        지도.스캔_넣기(포즈, 스캔)
    return 지도
