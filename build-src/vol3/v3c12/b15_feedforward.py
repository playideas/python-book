import mujoco
import numpy as np

from 계단지표 import 계단_지표, 지표_글
from 실전PID import 실전PID
from 진자장면 import XML, 실행


def 중력_계산기(질량_배율: float = 1.0):
    """진자 모델로 각도마다 qfrc_bias를 계산하는 함수. 질량_배율로 모델이 틀린 경우를 흉내 낸다."""
    모델 = mujoco.MjModel.from_xml_string(XML)
    모델.body_mass[1:] *= 질량_배율
    데이터 = mujoco.MjData(모델)

    def 중력(각도: float) -> float:
        데이터.qpos[0], 데이터.qvel[0] = 각도, 0.0
        mujoco.mj_forward(모델, 데이터)
        return float(데이터.qfrc_bias[0])
    return 중력


def 앞먹임_붙이기(제어기: 실전PID, 중력):
    """목표 자세를 버티는 데 드는 토크를 미리 계산해 PID 출력에 더한다."""
    return lambda 목표값, 측정: 제어기(목표값, 측정, 앞먹임=중력(목표값))


목표 = np.deg2rad(60)
분리 = np.deg2rad(5)                       # 적분 분리: 오차가 5도 안일 때만 적분한다
경우들 = {
    "PD                         ": 실전PID(30, 0, 5.7, 0.01),
    "PD + 앞먹임                 ": 앞먹임_붙이기(실전PID(30, 0, 5.7, 0.01), 중력_계산기()),
    "PD + 앞먹임(질량 80%)        ": 앞먹임_붙이기(실전PID(30, 0, 5.7, 0.01), 중력_계산기(0.8)),
    "PID                        ": 실전PID(30, 30, 5.7, 0.01),
    "PID + 앞먹임(질량 80%)       ": 앞먹임_붙이기(실전PID(30, 30, 5.7, 0.01), 중력_계산기(0.8)),
    "PID + 적분 분리              ": 실전PID(30, 30, 5.7, 0.01, 적분_구간=분리),
    "PID + 적분 분리 + 앞먹임(80%) ": 앞먹임_붙이기(실전PID(30, 30, 5.7, 0.01, 적분_구간=분리),
                                       중력_계산기(0.8)),
}
for 이름, 제어기 in 경우들.items():
    기록 = 실행(제어기, 목표, 시간=4.0)
    print(f"{이름}: " + 지표_글(계단_지표(기록["시각"], 기록["각도"], 0.0, 목표)))
