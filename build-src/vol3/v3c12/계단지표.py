"""12장: 계단 응답의 네 가지 지표를 기록에서 직접 계산한다."""
import numpy as np


def 계단_지표(시각: np.ndarray, 값: np.ndarray, 시작값: float, 목표값: float,
          띠: float = 0.02) -> dict[str, float]:
    """상승 시간(10%→90%), 오버슈트(%), 정착 시간(±2% 띠), 정상 상태 오차를 돌려준다.

    오차는 목표값 - 값이고, 정상 상태 오차는 마지막 10% 구간의 평균이다.
    정착하지 못했거나 90%에 닿지 못했으면 그 지표는 nan이다.
    """
    변화 = 목표값 - 시작값
    진행 = (값 - 시작값) / 변화                       # 0에서 출발해 1이 목표
    지표 = {"상승": np.nan, "오버슈트": max(진행.max() - 1, 0.0) * 100, "정착": np.nan}
    if (진행 >= 0.9).any():
        지표["상승"] = 시각[np.argmax(진행 >= 0.9)] - 시각[np.argmax(진행 >= 0.1)]
    밖 = np.abs(진행 - 1) > 띠
    if not 밖[-1]:                                    # 마지막에 띠 안이어야 정착한 것
        지표["정착"] = 시각[np.flatnonzero(밖)[-1] + 1] if 밖.any() else 시각[0]
    지표["오차"] = float(np.mean(목표값 - 값[-max(len(값) // 10, 1):]))
    return 지표


def 지표_글(지표: dict[str, float]) -> str:
    """표에 넣기 좋게 도 단위 한 줄로."""
    def 초(x: float) -> str:
        return "   -  " if np.isnan(x) else f"{x:5.2f}초"
    return (f"상승 {초(지표['상승'])}  오버슈트 {지표['오버슈트']:5.1f}%  "
            f"정착 {초(지표['정착'])}  정상 오차 {np.rad2deg(지표['오차']) + 0.0:6.2f}도")
