import numpy as np

from 계단지표 import 계단_지표, 지표_글
from 실전PID import 실전PID
from 진자장면 import 실행

목표 = np.deg2rad(60)
잡음 = np.deg2rad(0.5)                       # 각도 센서의 잡음(표준편차 0.5도)
주기 = 0.01
print(" 알파 | 시간 상수 | 토크 떨림 | 각도 떨림 | 계단 응답")
for 알파 in [1.0, 0.5, 0.2, 0.1, 0.05]:
    기록 = 실행(실전PID(30, 30, 5.7, 주기, 필터_알파=알파), 목표, 시간=4.0, 잡음=잡음)
    뒤 = 기록["시각"] >= 2.0                   # 자리 잡은 뒤 2초 동안의 떨림(표준편차)
    시간_상수 = (1 - 알파) * 주기 / 알파
    print(f" {알파:4.2f} | {시간_상수 * 1000:5.0f}ms | {기록['요청'][뒤].std():5.2f}N·m | "
          f"{np.rad2deg(기록['각도'][뒤].std()):6.3f}도 | "
          + 지표_글(계단_지표(기록["시각"], 기록["각도"], 0.0, 목표)))
