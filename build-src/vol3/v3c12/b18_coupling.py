import numpy as np

from 세로팔 import 실행, 토크_한계
from 실전PID import 실전PID


def 목표(t: float) -> np.ndarray:
    """0.5초에 어깨만 -90도(늘어뜨림) → 0도(수평)로 든다. 팔꿈치 목표는 줄곧 0도."""
    return np.deg2rad([-90 if t < 0.5 else 0, 0])


분리 = np.deg2rad(5)
for 이름, 보상 in [("관절별 PID", False), ("관절별 PID + 중력 보상 + 적분 분리", True)]:
    제어기들 = [실전PID(40, 40, 4, 0.01, 출력_한계=토크_한계[0], 적분_구간=분리 if 보상 else np.inf),
             실전PID(15, 15, 1, 0.01, 출력_한계=토크_한계[1], 적분_구간=분리 if 보상 else np.inf)]
    기록 = 실행(제어기들, 목표, 시간=2.5, 중력_보상=보상)
    팔꿈치_도 = np.rad2deg(기록["각도"][:, 1])
    든_뒤 = 기록["시각"] >= 0.5
    print(f"{이름}: 들기 전 팔꿈치 {np.abs(팔꿈치_도[~든_뒤]).max():.2f}도, "
          f"드는 동안 가장 크게 {팔꿈치_도[든_뒤].min():6.2f}도 ~ {팔꿈치_도[든_뒤].max():5.2f}도, "
          f"끝 {팔꿈치_도[-1]:5.2f}도")
