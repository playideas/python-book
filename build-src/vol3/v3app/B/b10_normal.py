import numpy as np

rng = np.random.default_rng(0)
잡음 = rng.normal(0.0, 0.02, size=100_000)            # 평균 0, 표준편차 0.02의 정규분포
print(f"평균 {잡음.mean():+.5f}, 표준편차 {잡음.std():.5f}, 분산 {잡음.var():.6f}")
for k in [1, 2, 3]:
    print(f"±{k}σ 안에 든 비율: {np.mean(np.abs(잡음) < k * 0.02):.1%}")

# 같은 것을 두 센서로 잰 값 합치기(8장): 분산의 역수로 가중 평균하면 분산이 줄어든다
값1, 분산1 = 10.0, 0.3**2                              # 흔들림이 큰 센서
값2, 분산2 = 10.4, 0.1**2                              # 흔들림이 작은 센서
분산 = 1 / (1 / 분산1 + 1 / 분산2)
값 = 분산 * (값1 / 분산1 + 값2 / 분산2)
print(f"합친 값 {값:.3f}, 표준편차 {np.sqrt(분산):.4f} (두 센서 0.3, 0.1보다 작다)")
