# 세탁기: 정해진 순서를 정해진 시간만큼 실행한다. 빨래 상태는 보지 않는다
세탁기_순서 = [("물 받기", 3), ("세탁", 20), ("헹굼", 10), ("탈수", 7)]
for 단계, 분 in 세탁기_순서:
    print(f"[세탁기] {단계} {분}분")

# 로봇 청소기: 매번 앞을 재고(감지), 그 값으로 할 일을 고르고(판단), 움직인다(행동)
안전_거리 = 0.2                                   # m. 이보다 가까우면 방향을 바꾼다
앞_거리_측정값 = [1.2, 0.8, 0.45, 0.15, 0.9, 0.6]  # 예제용: 매 순간 잰 앞 벽까지의 거리(m)
for 거리 in 앞_거리_측정값:
    행동 = "앞으로 간다" if 거리 > 안전_거리 else "제자리에서 돈다"
    print(f"[청소기] 앞 {거리:.2f}m → {행동}")
