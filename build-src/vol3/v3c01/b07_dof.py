# 관절 하나가 허락하는 독립 방향의 수
관절_자유도 = {"회전": 1, "직선": 1, "공": 3}

# 로봇 팔들을 관절 목록으로 적어 보기(어깨에서 손끝 쪽으로)
로봇_팔들 = {
    "평면 2관절 팔": ["회전", "회전"],
    "스카라 팔(조립용)": ["회전", "회전", "직선", "회전"],
    "6축 산업용 팔": ["회전"] * 6,
    "사람 팔(어깨~손목)": ["공", "회전", "회전", "회전", "회전"],   # 어깨, 팔꿈치, 아래팔 비틀기, 손목 두 방향
}
for 이름, 관절들 in 로봇_팔들.items():
    합 = sum(관절_자유도[관절] for 관절 in 관절들)
    print(f"{이름}: 관절 {len(관절들)}개, 자유도 {합}")

# 공중에 떠 있는 물체 하나가 가진 자유도: 위치 3 + 자세 3
print("공간 속 물체:", 3 + 3, "/ 바닥 위 물체(앞뒤·좌우·제자리 돌기):", 2 + 1)
