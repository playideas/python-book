"""1.8절 실습: 장애물 하나가 있는 평면에서 감지·판단·행동 고리를 도는 도구."""
import numpy as np

from 점로봇 import 속도_제한, 최대_속도, 움직이기, 위치_재기

시작, 목표 = np.array([0.0, 0.0]), np.array([2.0, 1.0])
장애물_중심, 장애물_반지름 = np.array([1.0, 0.5]), 0.25    # 둥근 기둥 하나(곧은 길 한가운데)
감지_범위 = 0.4             # 장애물 표면까지 이 거리(m) 안이면 센서가 알아챈다
주기, 이득 = 0.1, 1.5


def 장애물_감지(잰_위치: np.ndarray) -> tuple[float, np.ndarray] | None:
    """감지: 범위 안이면 (표면까지 거리, 장애물에서 로봇 쪽을 향한 단위 벡터), 아니면 None."""
    차이 = 잰_위치 - 장애물_중심
    중심_거리 = np.linalg.norm(차이)
    표면_거리 = 중심_거리 - 장애물_반지름
    if 표면_거리 > 감지_범위:
        return None
    return 표면_거리, 차이 / 중심_거리


def 판단(잰_위치: np.ndarray, 감지: tuple[float, np.ndarray] | None,
       밀어내기: bool, 옆으로: bool) -> np.ndarray:
    """판단: 규칙 몇 줄로 이번 주기의 속도 명령을 고른다."""
    속도 = 속도_제한(이득 * (목표 - 잰_위치))                # 규칙 1: 목표 쪽으로(비례 제어)
    if 감지 is None:
        return 속도
    거리, 바깥 = 감지
    세기 = 최대_속도 * 2 * (1 - 거리 / 감지_범위)            # 가까울수록 0에서 1m/s까지 커진다
    if 밀어내기:
        속도 = 속도 + 세기 * 바깥                            # 규칙 2: 장애물에서 멀어지는 쪽으로
    if 옆으로:
        둘레 = np.array([-바깥[1], 바깥[0]])                  # 바깥 방향을 왼쪽으로 직각만큼 튼 방향
        if np.dot(둘레, 목표 - 잰_위치) < 0:
            둘레 = -둘레                                     # 목표에 가까워지는 쪽 둘레를 고른다
        속도 = 속도 + 세기 * 둘레                            # 규칙 3: 장애물 둘레를 따라 비켜 간다
    return 속도


def 달리기(밀어내기: bool, 옆으로: bool, 생성기: np.random.Generator | None = None,
         미끄러짐: float = 0.0, 센서_잡음: float = 0.0, 걸음_수: int = 150) -> np.ndarray:
    """고리를 걸음_수만큼 돌고, 지나간 위치들을 (걸음_수+1, 2) 배열로 돌려준다."""
    위치, 경로 = 시작.copy(), [시작.copy()]
    for _ in range(걸음_수):
        잰_위치 = 위치_재기(위치, 생성기, 센서_잡음)              # 감지 1: 내 위치
        감지 = 장애물_감지(잰_위치)                               # 감지 2: 장애물
        속도_명령 = 판단(잰_위치, 감지, 밀어내기, 옆으로)         # 판단
        위치 = 움직이기(위치, 속도_명령, 주기, 생성기, 미끄러짐)   # 행동
        경로.append(위치)
    return np.array(경로)


def 결과(경로: np.ndarray) -> str:
    """경로가 장애물에 부딪혔는지, 목표에 닿았는지 한 줄로."""
    가장_가까이 = (np.linalg.norm(경로 - 장애물_중심, axis=1) - 장애물_반지름).min()
    남은_거리 = np.linalg.norm(목표 - 경로[-1])
    상태 = "[X] 충돌" if 가장_가까이 < 0 else ("[O] 도착" if 남은_거리 < 0.05 else "[!] 못 감")
    return f"{상태}: 장애물 표면과 가장 가까울 때 {가장_가까이:+.3f}m, 목표까지 {남은_거리:.3f}m"
