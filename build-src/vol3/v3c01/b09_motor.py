import numpy as np

주기 = 0.001                    # 1ms 간격으로 모터를 흉내 낸다

# DC 모터: 전압을 넣어도 속도가 바로 나지 않고 서서히 따라간다(시간 상수 0.05초)
시간_상수 = 0.05
명령_속도, 속도 = 10.0, 0.0       # rad/s
기록 = []
for _ in range(300):
    속도 += (명령_속도 - 속도) * 주기 / 시간_상수
    기록.append(속도)
기록 = np.array(기록)
for 비율 in [0.63, 0.95]:
    print(f"DC 모터: 명령의 {비율:.0%}에 닿기까지 {(np.argmax(기록 >= 비율 * 명령_속도) + 1) * 주기:.3f}초")

# 서보: DC 모터 + 각도 센서 + 작은 제어기. 안에서 닫힌 고리가 돈다
목표_각도_도, 각도_도, 속도 = 90.0, 0.0, 0.0
for 걸음 in range(1, 601):
    속도_명령 = np.clip(8.0 * (목표_각도_도 - 각도_도), -360, 360)   # 남은 각도에 비례, 최대 초당 360도
    속도 += (속도_명령 - 속도) * 주기 / 시간_상수                   # 모터는 명령을 서서히 따라간다
    각도_도 += 속도 * 주기
    if 걸음 % 100 == 0:
        print(f"서보 {걸음 * 주기:.1f}초: {각도_도:6.2f}도")
