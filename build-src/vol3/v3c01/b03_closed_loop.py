import numpy as np

from 점로봇 import 움직이기, 위치_재기

목표 = np.array([2.0, 1.0])
주기 = 0.1
이득 = 1.5                  # 남은 거리 1m당 1.5m/s로 가라는 뜻(비례 제어)

위치 = np.array([0.0, 0.0])
for 걸음 in range(80):                        # 8초 동안
    잰_위치 = 위치_재기(위치)                   # 1) 감지: 지금 어디인가
    속도_명령 = 이득 * (목표 - 잰_위치)          # 2) 판단: 남은 만큼에 비례해 가자
    위치 = 움직이기(위치, 속도_명령, 주기)       # 3) 행동: 한 주기 움직인다
    if 걸음 % 10 == 9:
        print(f"{(걸음 + 1) * 주기:3.1f}초: 위치 {np.round(위치, 3)}, 남은 거리 {np.linalg.norm(목표 - 위치):.3f}m")
