import numpy as np

목표, 이득, 주기 = 1.0, 4.0, 0.02      # 앞 실험에서 가장 얌전했던 0.02초 주기
for 늦음 in [0.0, 0.1, 0.2, 0.3, 0.4]:
    늦은_박자 = round(늦음 / 주기)          # 측정이 몇 박자 늦게 도착하나
    x, 기록 = 0.0, [0.0]
    for _ in range(round(6.0 / 주기)):         # 6초 동안
        잰_x = 기록[max(len(기록) - 1 - 늦은_박자, 0)]   # 늦음만큼 예전의 위치를 지금 받는다
        x = x + 이득 * (목표 - 잰_x) * 주기
        기록.append(x)
    기록 = np.array(기록)
    print(f"측정이 {늦음:.1f}초 늦으면: 최대 지나침 {max(기록.max() - 목표, 0):.3f}m, "
          f"마지막 1초 동안 흔들림 폭 {np.ptp(기록[-50:]):.3f}m")
