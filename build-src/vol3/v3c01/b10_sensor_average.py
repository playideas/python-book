import numpy as np

생성기 = np.random.default_rng(0)
참_거리 = 1.0           # m. 벽까지의 진짜 거리
잡음 = 0.02             # 거리 센서 한 번 읽기의 잡음(표준편차, m)

for 횟수 in [1, 4, 16, 64]:
    # '횟수'번 읽어 평균 내기를 1000번 해 보고, 그 평균들이 얼마나 흔들리는지 잰다
    읽기 = 참_거리 + 생성기.normal(0, 잡음, size=(1000, 횟수))
    평균들 = 읽기.mean(axis=1)
    print(f"{횟수:2d}번 평균: 흔들림(표준편차) {평균들.std():.4f}m")
