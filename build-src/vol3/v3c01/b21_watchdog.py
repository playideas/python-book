import numpy as np

from 점로봇 import 움직이기

목표 = np.array([1.0, 0.0])
주기, 이득 = 0.1, 1.5
감시_한계 = 0.3                            # 새 측정값 없이 이만큼(초) 지나면 멈춘다
센서_끊김 = (1.0, 2.5)                      # 이 시간 동안 센서 값이 오지 않는다(선이 빠졌다고 치자)

for 감시견_켜기 in [False, True]:
    위치 = np.array([0.0, 0.0])
    마지막_측정, 마지막_시각 = 위치.copy(), 0.0
    멈춘_횟수, 가장_멀리 = 0, 0.0
    for 걸음 in range(50):
        t = 걸음 * 주기
        if not (센서_끊김[0] <= t < 센서_끊김[1]):
            마지막_측정, 마지막_시각 = 위치.copy(), t          # 새 측정값이 도착했다
        if 감시견_켜기 and t - 마지막_시각 > 감시_한계:
            속도_명령 = np.zeros(2)                          # 측정이 너무 오래됐다: 멈춤
            멈춘_횟수 += 1
        else:
            속도_명령 = 이득 * (목표 - 마지막_측정)           # 가진 측정값 중 가장 최근 것으로 판단
        위치 = 움직이기(위치, 속도_명령, 주기)
        가장_멀리 = max(가장_멀리, 위치[0])
    print(f"감시견 {'켬' if 감시견_켜기 else '끔'}: 가장 멀리 x {가장_멀리:.3f}m, "
          f"멈춘 주기 {멈춘_횟수}번, 마지막 위치 x {위치[0]:.3f}m")
