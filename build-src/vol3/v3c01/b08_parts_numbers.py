import numpy as np

# 엔코더: 바퀴가 돈 만큼 눈금(펄스)을 센다
바퀴_반지름 = 0.035                  # m
한바퀴_눈금 = 1024                   # 한 바퀴에 나오는 눈금 수
눈금당_거리 = 2 * np.pi * 바퀴_반지름 / 한바퀴_눈금
print(f"눈금 하나 = {눈금당_거리 * 1000:.3f}mm")

실제_이동 = 0.5                       # 바퀴가 실제로 굴러간 거리(m)
센_눈금 = int(실제_이동 / 눈금당_거리)  # 엔코더는 다 채운 눈금만 센다
print(f"0.5m 굴렀을 때 센 눈금 {센_눈금}개 → 계산한 거리 {센_눈금 * 눈금당_거리:.5f}m")

# 스테핑 모터: 명령 한 번에 정해진 각도만큼 '딸깍' 돈다
걸음_각도_도 = 1.8
print(f"한 바퀴 = {360 / 걸음_각도_도:.0f}걸음, 90도 = {90 / 걸음_각도_도:.0f}걸음")
print(f"한 걸음을 16조각으로 나누면(마이크로스텝) 한 바퀴 = {360 / 걸음_각도_도 * 16:.0f}조각")
