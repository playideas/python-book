import numpy as np

from 강화도구 import 할인_반환값

# 1) 막대를 끝까지(1000걸음) 세운 판: 매 걸음 보상 1
for 감마 in [0.9, 0.99, 0.999]:
    G = 할인_반환값([1.0] * 1000, 감마)
    print(f"γ={감마}: 처음 G={G[0]:7.2f}, 1/(1-γ)={1 / (1 - 감마):7.1f}, 끝나기 10걸음 전 G={G[-10]:.2f}")

# 2) 지금 받는 작은 보상 1 vs 50걸음 뒤에 받는 큰 보상 10
지금_작게 = [1.0] + [0.0] * 50
나중_크게 = [0.0] * 50 + [10.0]
for 감마 in [0.9, 0.99]:
    print(f"γ={감마}: 지금 1 → {할인_반환값(지금_작게, 감마)[0]:.2f}, "
          f"50걸음 뒤 10 → {할인_반환값(나중_크게, 감마)[0]:.2f}")
print("γ=0.99에서 보상의 무게가 절반이 되는 걸음 수:", round(float(np.log(0.5) / np.log(0.99)), 1))
