import numpy as np

# 4×6 방. 로봇 청소기가 왼쪽 아래(S)에서 오른쪽 아래 충전기(C)로 간다. 아래 줄 가운데는 계단(#)
방 = ["......",
      "......",
      "......",
      "S####C"]
행_수, 열_수 = len(방), len(방[0])
움직임 = [(-1, 0), (1, 0), (0, -1), (0, 1)]             # 위, 아래, 왼쪽, 오른쪽
화살표 = "^v<>"
시작, 충전기 = (3, 0), (3, 5)


def 한_걸음(칸: tuple[int, int], 행동: int) -> tuple[tuple[int, int], float, bool]:
    """환경: 칸과 행동을 받아 (다음 칸, 보상, 끝남)을 돌려준다."""
    행 = min(max(칸[0] + 움직임[행동][0], 0), 행_수 - 1)
    열 = min(max(칸[1] + 움직임[행동][1], 0), 열_수 - 1)
    if 방[행][열] == "#":
        return 시작, -100.0, False                        # 계단에서 굴러 처음 자리로
    return (행, 열), -1.0, (행, 열) == 충전기              # 한 걸음마다 배터리 -1


생성기 = np.random.default_rng(0)
Q = np.zeros((행_수, 열_수, 4))                           # 칸마다 행동 넷의 점수표
학습률, 감마, 탐험_비율 = 0.5, 0.99, 0.1
for 판 in range(500):
    칸, 끝남 = 시작, False
    while not 끝남:
        if 생성기.random() < 탐험_비율:
            행동 = int(생성기.integers(4))                  # 탐험: 아무 쪽으로
        else:
            행동 = int(np.argmax(Q[칸]))                   # 활용: 점수가 가장 높은 쪽으로
        다음_칸, 보상, 끝남 = 한_걸음(칸, 행동)
        목표 = 보상 + (0.0 if 끝남 else 감마 * Q[다음_칸].max())
        Q[칸][행동] += 학습률 * (목표 - Q[칸][행동])        # 점수를 목표 쪽으로 조금 옮긴다
        칸 = 다음_칸

for 행 in range(행_수):
    print(" ".join(방[행][열] if 방[행][열] in "#C" else 화살표[np.argmax(Q[행, 열])] for 열 in range(열_수)))
칸, 경로 = 시작, 0
while 칸 != 충전기:
    칸, _, _ = 한_걸음(칸, int(np.argmax(Q[칸])))
    경로 += 1
print("학습한 대로 가면", 경로, "걸음 / 시작 칸의 점수:", np.round(Q[시작], 1))
