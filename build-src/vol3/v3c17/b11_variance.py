import numpy as np

생성기 = np.random.default_rng(0)
평균, 표준편차 = 0.0, 0.5


def 기울기_어림(보상_더하기: float, 기준선: bool) -> float:
    """16번 던져 본 결과로 '평균을 어느 쪽으로 옮길까'를 한 번 어림한다(REINFORCE)."""
    행동들 = 생성기.normal(평균, 표준편차, 16)
    보상들 = -(행동들 - 1.5) ** 2 + 보상_더하기
    if 기준선:
        보상들 = 보상들 - 보상들.mean()                   # 이번에 받은 보상의 평균을 기준으로
    로그확률_기울기 = (행동들 - 평균) / 표준편차 ** 2       # d log π(a) / d 평균
    return float(np.mean(로그확률_기울기 * 보상들))


print("참값(평균을 늘려야 하는 정도): 3.0")
for 이름, 더하기, 기준선 in [("보상 그대로", 0, False), ("모든 보상 +100", 100, False),
                         ("+100 후 기준선 빼기", 100, True)]:
    어림들 = np.array([기울기_어림(더하기, 기준선) for _ in range(2000)])
    틀린_방향 = np.mean(어림들 < 0) * 100
    print(f"{이름:14s}: 어림의 평균 {어림들.mean():6.2f}, 표준편차 {어림들.std():6.2f}, 반대 방향 {틀린_방향:4.1f}%")
