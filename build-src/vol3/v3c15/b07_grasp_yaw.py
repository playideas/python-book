import numpy as np

from 잡기도구 import TCP_포즈, 역기구학, 요_고르기, 집기_포즈, 포즈_오차
from 팔집게장면 import 집_자세

상자_높이 = 0.425                                   # 탁자 0.4m + 상자 반높이 2.5cm: TCP를 상자 가운데에


def 풀어_보기(위치, 요_도: float) -> tuple[np.ndarray, float, float]:
    """출발 자세에서 역기구학을 풀고, 남은 위치 오차(mm)와 자세 오차(도)를 함께 돌려준다."""
    T = 집기_포즈(위치, 요_도)
    q = 역기구학(T, 집_자세)
    e = 포즈_오차(T, TCP_포즈(q))
    return q, np.linalg.norm(e[:3]) * 1000, np.rad2deg(np.linalg.norm(e[3:]))


for 상자, 상자_요 in [((0.45, 0.15), 30), ((0.45, 0.15), 120), ((0.8, 0.0), 0)]:
    위치 = [*상자, 상자_높이]
    print(f"상자 {상자}, 요 {상자_요}도")
    for 요 in [상자_요, 상자_요 - 180]:
        q, 위치_mm, 자세_도 = 풀어_보기(위치, 요)
        print(f"  집게 요 {요:4d}도 → 관절 {np.round(np.rad2deg(q)).astype(int)}도, "
              f"손목3 {np.rad2deg(q[5] - 집_자세[5]):+6.1f}도 돌림, 남은 오차 {위치_mm:.1f}mm·{자세_도:.1f}도")
    if 위치_mm < 1:
        print(f"  요_고르기 → {요_고르기(위치, 상자_요, 집_자세):.0f}도")

# 사전 접근 자세(10cm 위)와 집는 자세는 관절이 조금만 다르다
q_위 = 역기구학(집기_포즈([0.45, 0.15, 상자_높이 + 0.1], 30), 집_자세)
q_집기 = 역기구학(집기_포즈([0.45, 0.15, 상자_높이], 30), q_위)
print("사전 접근 → 집기 관절 변화(도):", np.round(np.rad2deg(q_집기 - q_위), 1) + 0.0)
