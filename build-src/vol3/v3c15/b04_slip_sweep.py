import numpy as np

from 집게시험장면 import 들기, 만들기, 흘려보내기

질량, 마찰 = 0.2, 1.0                      # 상자 마찰 0.5와 패드 1.0 중 큰 값이 쓰인다
최소 = 질량 * 9.81 / (2 * 마찰)
print(f"식으로 구한 최소 쥐는 힘: {최소:.3f}N")


def 들어_보기(쥐는_힘: float, 옵션: str) -> float:
    """쥐고 1초 동안 6.5cm 들어 올리고 0.5초 기다린 뒤, 상자가 손가락 안에서 미끄러져 내려간 거리(mm)."""
    모델, 데이터 = 만들기(쥐는_힘=쥐는_힘, 상자_질량=질량, 옵션=옵션)
    데이터.ctrl[모델.actuator("grip").id] = 0.0                 # 끝까지 닫으라고 명령
    흘려보내기(모델, 데이터, 0.5)
    처음 = 데이터.site("tcp").xpos[2] - 데이터.body("box").xpos[2]
    들기(모델, 데이터, 0.065)
    return (데이터.site("tcp").xpos[2] - 데이터.body("box").xpos[2] - 처음) * 1000


print("쥐는 힘 | 최소의 몇 배 | 미끄러짐: 기본 설정 | 타원 원뿔 + impratio=10")
for 쥐는_힘 in [0.8, 0.95, 1.0, 1.1, 1.5, 3.0, 10.0]:
    기본 = 들어_보기(쥐는_힘, "")
    타원 = 들어_보기(쥐는_힘, 'cone="elliptic" impratio="10"')
    print(f" {쥐는_힘:5.2f}N | {쥐는_힘 / 최소:7.2f}배 | {np.round(기본, 1):8.1f}mm | {np.round(타원, 1):8.1f}mm")
