from 집게시험장면 import 들기, 만들기, 흘려보내기

쥐는_힘 = {"가) 보통": 10.0, "나) 상자가 없다": 10.0, "다) 너무 약하게": 0.8}


def 잡고_있나(데이터, 힘: float) -> str:
    """두 손가락 모두 쥐는 힘의 절반 이상을 느끼고, 너비가 1cm보다 넓어야 잡은 것."""
    왼, 오 = 데이터.sensor("touch_l").data[0], 데이터.sensor("touch_r").data[0]
    너비 = 데이터.sensor("width").data[0]
    판단 = "잡음" if min(왼, 오) > 0.5 * 힘 and 너비 > 0.01 else "못 잡음"
    return f"접촉 {왼:5.2f}N / {오:5.2f}N, 너비 {너비 * 100:4.1f}cm → {판단}"


for 경우, 힘 in 쥐는_힘.items():
    모델, 데이터 = 만들기(쥐는_힘=힘, 상자_질량=0.2, 상자_y=0.2 if "없다" in 경우 else 0.0)
    데이터.ctrl[모델.actuator("grip").id] = 0.0
    흘려보내기(모델, 데이터, 0.5)
    print(f"{경우:10s} 쥔 직후  : {잡고_있나(데이터, 힘)}")
    들기(모델, 데이터, 0.06)
    print(f"{'':10s} 6cm 든 뒤: {잡고_있나(데이터, 힘)}")
