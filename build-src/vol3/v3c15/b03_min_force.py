g = 9.81


def 최소_쥐는_힘(질량: float, 마찰: float, 손가락_수: int = 2, 가속도: float = 0.0) -> float:
    """손가락마다 눌러야 하는 최소 수직력(N). 마찰력 합 μ·N·손가락_수 ≥ m(g + a)."""
    return 질량 * (g + 가속도) / (마찰 * 손가락_수)


print("물체               | μ   | 최소 힘 | 안전율 2배")
for 이름, 질량, 마찰 in [("0.2kg 상자, 고무 패드", 0.2, 1.0), ("0.2kg 상자, 플라스틱", 0.2, 0.3),
                     ("1kg 병, 고무 패드", 1.0, 1.0), ("1kg 병, 젖은 유리", 1.0, 0.1)]:
    힘 = 최소_쥐는_힘(질량, 마찰)
    print(f"{이름:17s}| {마찰:.1f} | {힘:5.2f}N | {2 * 힘:5.2f}N")
print(f"0.2kg 상자를 2m/s²로 들어 올리면: {최소_쥐는_힘(0.2, 1.0, 가속도=2.0):.2f}N")
