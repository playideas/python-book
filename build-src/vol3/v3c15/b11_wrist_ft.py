import numpy as np

from 집게시험장면 import 들기, 만들기, 흘려보내기

print("상자 질량 | 들기 전 손목 힘 z | 든 뒤 z | 차이로 잰 질량")
for 질량 in [0.05, 0.1, 0.2, 0.5]:
    모델, 데이터 = 만들기(쥐는_힘=10.0, 상자_질량=질량)
    영점 = 데이터.sensor("wrist_force").data.copy()             # 빈손일 때: 집게 자신의 무게
    데이터.ctrl[모델.actuator("grip").id] = 0.0
    흘려보내기(모델, 데이터, 0.5)
    들기(모델, 데이터, 0.06)
    힘 = 데이터.sensor("wrist_force").data
    print(f"  {질량:.2f}kg | {영점[2]:8.3f}N | {힘[2]:7.3f}N | {(영점[2] - 힘[2]) / 9.81:.3f}kg")

# 상자 끝을 잡으면? 무게 중심이 손가락에서 벗어난 만큼 손목에 토크가 걸린다
모델, 데이터 = 만들기(쥐는_힘=10.0, 상자_질량=0.2, 상자_x=0.035)
데이터.ctrl[모델.actuator("grip").id] = 0.0
흘려보내기(모델, 데이터, 0.5)
들기(모델, 데이터, 0.06)
토크 = 데이터.sensor("wrist_torque").data
print(f"상자 가운데에서 3.5cm 떨어진 곳을 잡음 → 손목 토크 {np.round(토크, 4) + 0.0}N·m, "
      f"무게 중심까지 거리 추정 {np.linalg.norm(토크) / (0.2 * 9.81) * 100:.1f}cm")
