from 계획도구 import 규칙_계획
from 지시수행 import 이름표

이름들 = list(이름표)                        # 19.4절에서 카메라가 찾은 이름들
지시들 = ["빨간 상자를 파란 그릇에 넣어 줘", "공을 그릇에 담아", "노란 컵이랑 초록 상자를 그릇에 넣어",
         "빨간 걸 그릇에 넣어", "상자를 그릇에 넣어", "그릇 안에 초록 상자 좀 넣어 줄래?",
         "빨간 상자를 창밖으로 던져 줘", "초록 상자는 그릇에 넣지 마"]
for 지시 in 지시들:
    계획 = 규칙_계획(지시, 이름들)
    글 = " → ".join(f"{단계['기술']}({단계['대상']})" for 단계 in 계획) or "(못 알아들음)"
    print(f"{지시:24s} | {글}")
