from 팔집게장면 import 준비

# 장면 이름 → 검출기에 줄 영어 글. OWLv2는 영어 글과 사진의 짝으로 학습했다
이름표 = {"빨간 상자": "a red box", "초록 상자": "a green box", "빨간 공": "a red ball",
         "노란 컵": "a yellow cup", "파란 그릇": "a blue bowl"}


def 장면_읽기(모델, 데이터, 검출기, 컬러, 깊이) -> dict[str, dict]:
    """이름표의 물체를 사진에서 찾아 {이름: 잰 값}. 찾지 못한 물체는 장면에 없다."""
    점들 = 점구름(모델, 데이터, 깊이)
    장면 = {}
    for 이름, (점수, 상자) in 검출기.찾기(컬러, list(이름표.values())).items():
        이름 = next(한글 for 한글, 영어 in 이름표.items() if 영어 == 이름)
        if (잰 := 상자_재기(점들, 상자, 반경=0.12 if 이름 == "파란 그릇" else 0.06)) is not None:
            장면[이름] = {**잰, "점수": 점수, "상자": 상자}
    return 장면


def 집게_요(이름: str, 장면: dict[str, dict]) -> float:
    """상자는 잰 요 그대로(좁은 쪽을 집는다). 둥근 물체는 요가 의미 없으니,
    손가락이 가장 가까운 이웃 쪽으로 벌어지지 않게 이웃을 향한 방향과 직각으로 벌린다."""
    물체 = 장면[이름]
    if 물체["길이"] - 물체["폭"] > 0.01:
        return 물체["요_도"]
    이웃 = min((값 for 남, 값 in 장면.items() if 남 != 이름),
             key=lambda 값: np.linalg.norm(값["중심"][:2] - 물체["중심"][:2]))
    차이 = 이웃["중심"][:2] - 물체["중심"][:2]
    return float(np.rad2deg(np.arctan2(차이[1], 차이[0])))    # 집게 요 = 이웃 방향이면 손가락은 그 직각으로


def 계획_실행(모델, 데이터, 계획: list[dict], 장면: dict[str, dict], 찍기=None,
            요_정하기=집게_요) -> list[tuple[str, bool, str]]:
    """집기·놓기 한 쌍마다 15장의 상태 기계를 돌린다. 실패하면 거기서 멈춘다."""
    준비(모델, 데이터)
    결과 = []
    for 집기, 놓기 in zip(계획[::2], 계획[1::2]):
        물체, 장소 = 장면[집기["대상"]], 장면[놓기["대상"]]
        놓을_곳 = np.array([*장소["중심"][:2], 물체["중심"][2]])    # 그릇 가운데, 물체 가운데 높이
        q = 데이터.ctrl[:6].copy()
        작업 = 집고놓기(모델, 데이터, 물체["중심"], 요_고르기(물체["중심"], 요_정하기(집기["대상"], 장면), q),
                     놓을_곳, 요_고르기(놓을_곳, 0.0, q), 쥐는_힘=10.0)
        성공 = 작업.실행(최대_시간=데이터.time + 20, 찍기=찍기)
        결과.append((집기["대상"], 성공, 작업.기록[-1][2] or 작업.기록[-1][1]))
        if not 성공:
            break
    return 결과
