"""6자유도 팔의 야코비안(3.5절). 팔도구.py의 순기구학을 쓴다."""
import numpy as np

from 팔도구 import 손끝_위치, 순기구학, 예제_팔


def 야코비안(관절각, 팔=예제_팔, 손끝=손끝_위치) -> np.ndarray:
    """바닥 기준 6×n 야코비안. 위 세 줄은 손끝 속도, 아래 세 줄은 손끝 각속도."""
    좌표계들 = 순기구학(관절각, 팔, 손끝)
    p_끝 = 좌표계들[-1][:3, 3]
    J = np.zeros((6, len(팔)))
    for i, (_, _, 축) in enumerate(팔):
        z = 좌표계들[i][:3, :3] @ np.asarray(축, dtype=float)   # 바닥에서 본 관절 축
        p = 좌표계들[i][:3, 3]                                  # 바닥에서 본 관절 위치
        J[:3, i] = np.cross(z, p_끝 - p)      # 축을 중심으로 돌면 손끝은 원을 그린다
        J[3:, i] = z                          # 손끝은 그 축을 중심으로 함께 돈다
    return J
