import mujoco
import numpy as np

from 계획도구 import 계획_검사, 규칙_계획
from 지시수행 import 계획_실행, 장면_읽기
from 지시장면 import 그릇_반지름, 그릇_중심, 장면_xml, 찍기
from 찾기도구 import 개방어휘검출기

검출기 = 개방어휘검출기()
지시들 = ["빨간 상자를 파란 그릇에 넣어 줘", "공을 그릇에 담아", "그릇 안에 초록 상자 좀 넣어 줄래?",
         "빨간 공이랑 초록 상자를 그릇에 넣어", "노란 컵을 그릇에 넣어", "빨간 상자를 창밖으로 던져 줘"]
for 지시 in 지시들:
    모델 = mujoco.MjModel.from_xml_string(장면_xml())      # 지시마다 처음 장면에서 시작
    데이터 = mujoco.MjData(모델)
    장면 = 장면_읽기(모델, 데이터, 검출기, *찍기(모델, 데이터))
    계획 = 규칙_계획(지시, list(장면))
    if 문제들 := 계획_검사(계획, 장면):
        print(f"{지시} → 거절: {' / '.join(문제들)}")
        continue
    결과 = 계획_실행(모델, 데이터, 계획, 장면)
    담긴것 = [이름 for 이름 in ("빨간 상자", "초록 상자", "빨간 공")
             if np.linalg.norm(데이터.body(이름).xpos[:2] - 그릇_중심) < 그릇_반지름]
    print(f"{지시} → {', '.join(f'{물체} {메모}' for 물체, _, 메모 in 결과)} / 그릇 안: {', '.join(담긴것)}"
          f" ({데이터.time:.1f}초)")
