import numpy as np

from 바퀴장면 import 달리기
from 실습도구 import ekf_돌리기, 오차

기록 = 달리기(100.0, np.random.default_rng(0))
경우들 = {
    "기본(표지 4개)": {},
    "표지 2개(위쪽)": {"쓸_표지": (0, 1)},
    "표지 1개": {"쓸_표지": (0,)},
    "Q를 100배 작게": {"Q_배율": 0.01},
    "Q를 100배 크게": {"Q_배율": 100.0},
    "R을 100배 작게": {"R_배율": 0.01},
}
print(" 경우              | 위치 평균 | 위치 최대 | 방향 평균 | 방향 최대")
for 이름, 설정 in 경우들.items():
    추정, _ = ekf_돌리기(기록, **설정)
    위치, 방향 = 오차(추정, 기록["참"])
    방향_도 = np.rad2deg(np.abs(방향))
    print(f" {이름:14s} | {위치.mean():.3f}m | {위치.max():.3f}m | {방향_도.mean():5.2f}도 | {방향_도.max():5.2f}도")
