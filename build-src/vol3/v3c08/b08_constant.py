import numpy as np

생성기 = np.random.default_rng(0)
참_거리, R = 1.0, 0.02**2          # 벽까지 1m, 거리 센서 잡음 표준편차 0.02m(분산 R)
Q = 0.0                             # 벽도 로봇도 움직이지 않는다

x, P = 0.0, 100.0                   # 처음에는 아무것도 모른다: 아무 값 + 아주 큰 분산
읽은_값들 = []
print("  n |  칼만 이득 K |   추정값  |  그냥 평균 | 추정의 표준편차")
for n in range(1, 101):
    x, P = x, P + Q                         # 예측: 값은 그대로, 불확실성은 Q만큼 커진다
    z = 참_거리 + 생성기.normal(0, 0.02)     # 측정
    K = P / (P + R)                         # 갱신: 얼마나 측정 쪽으로 옮길까
    x = x + K * (z - x)
    P = (1 - K) * P
    읽은_값들.append(z)
    if n in [1, 2, 3, 4, 10, 100]:
        print(f"{n:3d} | {K:10.4f} | {x:.5f} | {np.mean(읽은_값들):.5f} | {np.sqrt(P):.4f}m")
