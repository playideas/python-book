import numpy as np

from 흔들판 import rms_도, 가속도_피치, 기록하기, 센서_더하기, 주기

기록 = 기록하기()
자이로, 가속도 = 센서_더하기(기록, np.random.default_rng(0))
가속도_피치값 = 가속도_피치(가속도)
참값 = 기록["참_피치"]

print("  알파  | 시간 상수 | 오차 RMS | 떠는 구간 RMS")
for 알파 in [0.5, 0.9, 0.98, 0.995, 0.999]:
    피치, 결과 = 가속도_피치값[0], []
    for w, a in zip(자이로, 가속도_피치값):
        피치 = 알파 * (피치 + w * 주기) + (1 - 알파) * a
        결과.append(피치)
    오차 = np.array(결과) - 참값
    떠는_구간 = (기록["시간"] >= 12) & (기록["시간"] < 16)
    시간_상수 = 알파 * 주기 / (1 - 알파)
    print(f" {알파:.3f} | {시간_상수:6.2f}초 | {rms_도(오차):6.2f}도 | {rms_도(오차[떠는_구간]):6.2f}도")
