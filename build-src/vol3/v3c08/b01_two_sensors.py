import numpy as np

from 흔들판 import 가속도_피치, 기록하기, 센서_더하기, 주기

기록 = 기록하기()
자이로, 가속도 = 센서_더하기(기록, np.random.default_rng(0))

자이로_피치 = np.cumsum(자이로) * 주기          # 2장 방식: 각속도를 쌓는다(1차원이라 더하기면 된다)
가속도_피치값 = 가속도_피치(가속도)              # 7장 방식: 중력 방향으로 읽는다
참값 = 기록["참_피치"]

print(" 시각 |  참 피치 | 자이로 쌓기 | 가속도계")
for 초 in [1, 5, 13, 20, 30]:
    i = round(초 / 주기) - 1
    print(f"{초:4d}초 | {np.rad2deg(참값[i]):6.1f}도 | {np.rad2deg(자이로_피치[i]):8.1f}도 | {np.rad2deg(가속도_피치값[i]):6.1f}도")
