import numpy as np

from 회전도구 import Ry, Rz, 깔끔


def 변환(R: np.ndarray, p) -> np.ndarray:
    T = np.eye(4)
    T[:3, :3] = R
    T[:3, 3] = p
    return T


R_몸_카메라 = np.array([[0, 0, 1], [-1, 0, 0], [0, -1, 0]])     # 2.3절의 축 바꾸기

T_방_로봇 = 변환(Rz(90), [1.5, 0.0, 0.0])                    # 로봇: 방의 (1.5, 0)에서 왼쪽으로 90도
T_로봇_카메라 = 변환(Ry(30) @ R_몸_카메라, [0.1, 0.0, 0.5])  # 카메라: 앞 0.1m, 높이 0.5m, 30도 숙임

컵_카메라 = np.array([0.5, -0.017, 1.029, 1.0])   # 카메라가 알려 준 컵 위치(동차 좌표)

T_방_카메라 = T_방_로봇 @ T_로봇_카메라         # 이름의 안쪽 글자(로봇)가 맞물린다
print("방 기준 카메라 위치:", 깔끔(T_방_카메라[:3, 3]))
print("방 기준 카메라가 보는 방향:", 깔끔(T_방_카메라[:3, 2]))   # 카메라 z축 = 3번째 열
print("방 기준 컵 위치    :", 깔끔((T_방_카메라 @ 컵_카메라)[:3]))
print("로봇 기준 컵 위치  :", 깔끔((T_로봇_카메라 @ 컵_카메라)[:3]))
