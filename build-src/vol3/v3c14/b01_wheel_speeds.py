from 이동도구 import 바퀴에서_속도, 속도에서_바퀴

# 왼쪽·오른쪽 바퀴 각속도(rad/s) 다섯 쌍을 몸의 속도로 바꿔 본다
for 왼, 오른 in [(6, 6), (4, 8), (8, 4), (-4, 4), (0, 6)]:
    v, ω = 바퀴에서_속도(왼, 오른)
    반지름 = "직진" if ω == 0 else f"{v / ω:.3f}m"
    print(f"왼 {왼:3d}, 오른 {오른:3d} → v {v:.2f}m/s, ω {ω:6.3f}rad/s, 회전 반지름 {반지름}")

왼, 오른 = 속도에서_바퀴(0.3, 0.5)
print(f"되돌리기: v 0.3, ω 0.5 → 왼 {왼:.2f}, 오른 {오른:.2f}rad/s")
