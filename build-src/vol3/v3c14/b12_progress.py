from 감시도구 import 도착했나, 진척_감시

감시 = 진척_감시()
# 0.1m/s로 3초 가다가, 무언가에 막혀 0.01m/s로 겨우 꼼지락거리는 로봇
for k in range(200):
    시각 = k * 0.1
    x = 0.1 * min(시각, 3.0) + 0.01 * max(시각 - 3.0, 0.0)
    if 감시.막혔나((x, 0.0), 시각):
        print(f"{시각:.1f}초에 '막혔다' (위치 x {x:.2f}m, 기준점 x {감시.기준_위치[0]:.2f}m, 기준 시각 {감시.기준_시각:.1f}초)")
        break
print("목표 (1, 0)에서 0.2m 떨어진 곳:", 도착했나((0.8, 0.0), (1.0, 0.0)))
print("목표 (1, 0)에서 0.3m 떨어진 곳:", 도착했나((0.7, 0.0), (1.0, 0.0)))
