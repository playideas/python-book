import mujoco
import numpy as np

from 이동도구 import 바퀴에서_속도, 속도에서_바퀴
from 주행장면 import 로봇_포즈, 장면_만들기

# 빈 바닥 한가운데(사람·상자와 멀리)에서 바퀴 명령만 주고 몸이 실제로 어떻게 움직이는지 잰다
for v_명령, ω_명령 in [(0.3, 0.0), (0.3, 0.5), (0.0, 1.0)]:
    모델, 데이터 = 장면_만들기((2.0, 2.0, 0.0))
    데이터.ctrl[:] = 속도에서_바퀴(v_명령, ω_명령)
    옆_속도들 = []
    while 데이터.time < 2.0:
        mujoco.mj_step(모델, 데이터)
        θ = 로봇_포즈(데이터)[2]
        vx, vy = 데이터.qvel[0:2]                          # freejoint의 선속도는 방 기준
        옆_속도들.append(-np.sin(θ) * vx + np.cos(θ) * vy)  # 몸의 왼쪽 방향 성분
    # 출력용으로 반올림하고 + 0.0으로 -0.0을 0.0으로 바꾼다
    앞_속도, 몸_ω = np.round([np.cos(θ) * vx + np.sin(θ) * vy, 데이터.qvel[5]], 3) + 0.0
    바퀴_v, 바퀴_ω = np.round(바퀴에서_속도(데이터.qvel[6], 데이터.qvel[7]), 3) + 0.0
    print(f"명령 v {v_명령:.1f}, ω {ω_명령:.1f} → 몸 v {앞_속도:.3f}, ω {몸_ω:.3f}"
          f" (바퀴로 계산 v {바퀴_v:.3f}, ω {바퀴_ω:.3f}), 옆 속도 최대 {np.max(np.abs(옆_속도들)):.4f}m/s")
