import numpy as np

from 내비실습 import 목적지_하나, 장애물_층
from 주행장면 import 장면_만들기
from 지도도구 import 지도_그리기

# 지도에 없는 상자로 왼쪽 문까지 막는다. 오른쪽 복도의 상자와 함께 목적지 '나'로 가는 길이 모두 막혔다
문_막이 = '<geom type="box" pos="2.6 4 0.3" size="0.45 0.1 0.3" group="1" rgba="0.85 0.2 0.2 1"/>'
모델, 데이터 = 장면_만들기((1.5, 1.5, 0.0), 문_막이)
층 = 장애물_층(지도_그리기(모델))
기록 = 목적지_하나(모델, 데이터, 층, (8.5, 6.8))
for 시각, 사건 in 기록["사건"]:
    print(f"{시각:5.1f}초  {사건}")
x, y, _ = 기록["궤적"][-1]
print(f"도착: {'예' if 기록['도착'] else '아니요'}, 멈춘 곳 ({x:.2f}, {y:.2f}), 부딪힘 {기록['부딪힘']}번")
