최대_감속 = 1.0                  # 브레이크를 끝까지 밟았을 때의 감속(m/s²)
주기 = 0.1                       # 판단 주기(초)

for 속도 in [0.5, 1.0, 2.0]:                     # 지금 속도(m/s)
    멈추는_시간 = 속도 / 최대_감속
    멈추는_거리 = 속도**2 / (2 * 최대_감속)      # 등감속 운동: v² = 2·a·s
    print(f"{속도:.1f}m/s로 달리면: 멈추는 데 {멈추는_시간:.1f}초, {멈추는_거리:.3f}m "
          f"→ 적어도 {멈추는_시간 / 주기:.0f}주기 앞을 봐야 한다")
