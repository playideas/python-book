"""16장: 바퀴 둘 달린 로봇을 유니사이클로 본 모델과 장애물 장면. 상태 [x, y, θ](m, m, rad), 입력 [v, ω](m/s, rad/s)."""
import numpy as np

주기 = 0.1                                       # 제어 주기(초)
속도_한계 = (0.0, 0.6)                            # 앞으로만 간다(m/s)
회전_한계 = (-2.0, 2.0)                           # rad/s
로봇_반지름 = 0.15
목표 = np.array([4.0, 1.0])
# 장애물: 중심 x, 중심 y, 반지름(m). 앞을 막는 큰 기둥 하나와 좁은 문을 만드는 기둥 둘
장애물 = np.array([[1.5, 0.25, 0.45],
                [3.0, 1.62, 0.35],
                [3.0, 0.38, 0.35]])


def 굴리기(상태: np.ndarray, 입력들: np.ndarray) -> np.ndarray:
    """입력열((N,2))을 차례로 넣어 앞으로의 상태((N,3))를 예측한다."""
    x, y, θ = 상태
    기록 = np.empty((len(입력들), 3))
    for k, (v, ω) in enumerate(입력들):
        x, y, θ = x + v * np.cos(θ) * 주기, y + v * np.sin(θ) * 주기, θ + ω * 주기
        기록[k] = x, y, θ
    return 기록


def 여유(위치들: np.ndarray) -> np.ndarray:
    """각 위치에서 각 장애물 표면까지 남은 거리(로봇 반지름을 뺀 값). 음수면 부딪힌 것."""
    차이 = 위치들[:, None, :2] - 장애물[None, :, :2]
    return np.linalg.norm(차이, axis=2) - 장애물[None, :, 2] - 로봇_반지름
