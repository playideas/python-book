import numpy as np

from 이중적분기 import 굴리기, 비용

x0 = np.array([-1.0, 0.0])                    # 목표(원점)보다 1m 뒤에 서 있다
Q = np.diag([1.0, 0.1])                       # 위치 오차를 속도 오차보다 10배 무겁게
계획들 = {                                     # 4초(40주기) 동안의 가속도 계획(m/s²)
    # 1m/s²로 1초 밀고 1초 당겨 2초 만에 도착
    "급하게": np.r_[np.full(10, 1.0), np.full(10, -1.0), np.zeros(20)],
    # 0.25m/s²로 2초 밀고 2초 당겨 4초 만에 도착
    "느긋이": np.r_[np.full(20, 0.25), np.full(20, -0.25)],
    "가만히": np.zeros(40),
}
for R in [0.01, 1.0]:
    print(f"R = {R}")
    for 이름, 입력들 in 계획들.items():
        상태들 = 굴리기(x0, 입력들)
        오차, 힘 = 비용(상태들, 입력들, Q, R)
        print(f"  {이름} 끝 위치 {round(상태들[-1, 0], 2) + 0.0:5.2f}m | 오차 비용 {오차:5.2f} + 입력 비용 {힘:5.2f} = {오차 + 힘:5.2f}")
