"""18장: 15장의 집고 놓기 순서를 '지금 상태만 보고 다음 행동을 정하는' 스크립트 전문가로."""
import numpy as np

from 모방환경 import 높이, 놓을_곳, 닫힘, 열림, 제어_주기
from 잡기도구 import TCP_포즈, 역기구학, 집기_포즈

최대_속도 = 0.4           # TCP 목표를 한 걸음에 수평·수직 각각 0.4m/s × 0.02s = 8mm까지만 옮긴다
접근_높이 = 0.10
들기_높이 = 0.15


def 목표_정하기(환경) -> tuple[np.ndarray, float, str]:
    """(TCP가 갈 곳, 집게 명령, 단계 이름). 상태 기계의 단계를 기억하지 않고 지금 상태에서 읽는다."""
    d = 환경.데이터
    tcp, 상자 = d.site("tcp").xpos.copy(), d.body("box").xpos.copy()
    놓을 = np.array([*놓을_곳, 높이])
    위로 = lambda 곳, 얼마: np.array([곳[0], 곳[1], 얼마])       # 곳의 x, y에 높이만 바꾼 점
    if 환경.잡고_있나():
        if np.linalg.norm(tcp[:2] - 놓을[:2]) > 0.008:
            if tcp[2] < 높이 + 0.05:                             # 상자가 탁자에서 5cm 뜰 때까지는 곧게 위로
                return 위로(tcp, 높이 + 들기_높이), 닫힘, "들기"
            return 위로(놓을, 높이 + 들기_높이), 닫힘, "옮기기"
        if 상자[2] < 높이 + 0.003:                               # 상자가 탁자에 닿았다
            return tcp, 열림, "놓기"
        return 놓을 - [0, 0, 0.01], 닫힘, "내려놓기"
    if np.linalg.norm(상자[:2] - 놓을[:2]) < 0.03 and 상자[2] < 높이 + 0.01:
        if d.sensor("width").data[0] < 0.06:                   # 손가락이 다 열릴 때까지 그대로
            return tcp, 열림, "놓기"
        return 위로(tcp, 높이 + 접근_높이), 열림, "물러나기"
    if np.linalg.norm(tcp[:2] - 상자[:2]) > 0.008:
        if tcp[2] < 상자[2] + 접근_높이 - 0.03:                 # 상자 옆에서 낮게 있으면 먼저 올라간다
            return 위로(tcp, 상자[2] + 접근_높이), 열림, "올라가기"
        return 위로(상자, 상자[2] + 접근_높이), 열림, "다가가기"
    if tcp[2] > 상자[2] + 0.005:
        return 상자, 열림, "내려가기"
    return 상자, 닫힘, "쥐기"


def 요_정하기(q) -> float:
    """상자 요가 0이니 집게 요는 0도나 180도(15장). 지금 집게 방향에 가까운 쪽을 고른다."""
    R = TCP_포즈(q)[:3, :3]
    지금 = np.degrees(np.arctan2(R[1, 0], R[0, 0]))
    return 0.0 if abs((지금 + 180) % 360 - 180) < 90 else 180.0


def 전문가(환경) -> np.ndarray:
    """전문가의 행동 [관절 6개를 얼마나 더 돌릴지, 집게 명령]. 어떤 상태에서 물어도 답한다."""
    q = 환경.데이터.qpos[:6].copy()
    목표, 집게, _ = 목표_정하기(환경)
    tcp = 환경.데이터.site("tcp").xpos
    수평, 수직 = (목표 - tcp)[:2], (목표 - tcp)[2]
    한계 = 최대_속도 * 제어_주기
    수평 = 수평 * min(1.0, 한계 / max(np.linalg.norm(수평), 1e-9))
    걸음 = np.array([*수평, np.clip(수직, -한계, 한계)])
    q_목표 = 역기구학(집기_포즈(tcp + 걸음, 요_정하기(q)), q, 반복=10)     # 지금 관절에서 출발(15장)
    return np.concatenate([q_목표 - q, [집게]])
