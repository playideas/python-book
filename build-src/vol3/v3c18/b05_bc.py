from 시연도구 import 성공률, 시연_모으기, 시험_위치
from 정책도구 import 검증_손실, 학습

데이터 = 시연_모으기(250)
관측, 행동, 에피소드 = 데이터["관측"], 데이터["행동"], 데이터["에피소드"]
학습_칸, 검증_칸 = 에피소드 < 200, 에피소드 >= 200          # 에피소드 단위로 나눈다

정책 = 학습(관측[학습_칸], 행동[학습_칸])
print(f"학습 걸음 {학습_칸.sum():,}개, 검증 걸음 {검증_칸.sum():,}개")
print(f"검증 손실(정규화한 MSE): {검증_손실(정책, 관측[검증_칸], 행동[검증_칸]):.4f}")
print("검증 첫 걸음 전문가 행동:", 행동[검증_칸][0].round(4))
print("검증 첫 걸음 정책 행동  :", 정책(관측[검증_칸][0]).round(4))
print(f"처음 보는 상자 위치 50곳에서 성공률: {성공률(정책, 시험_위치(50)):.0%}")
