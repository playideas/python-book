"""3장 기구학 도구: 2장의 변환·역변환에 관절 회전과 순기구학을 더한다."""
import numpy as np


def 변환(R: np.ndarray, p) -> np.ndarray:
    """회전 R과 이동 p를 4×4 동차 변환 행렬 하나로 묶는다(2장 2.8절)."""
    T = np.eye(4)
    T[:3, :3] = R
    T[:3, 3] = p
    return T


def 역변환(T: np.ndarray) -> np.ndarray:
    """T의 반대 방향 변환. 회전은 전치, 이동은 -Rᵀp(2장 2.8절)."""
    R, p = T[:3, :3], T[:3, 3]
    return 변환(R.T, -R.T @ p)


def 이동(p) -> np.ndarray:
    """돌지 않고 p만큼 옮기는 변환."""
    return 변환(np.eye(3), p)


def 축_회전(축, 각: float) -> np.ndarray:
    """단위 축을 중심으로 각(rad)만큼 도는 변환. 2장 2.5절의 로드리게스 공식."""
    k = np.asarray(축, dtype=float)
    K = np.array([[0, -k[2], k[1]],
                  [k[2], 0, -k[0]],
                  [-k[1], k[0], 0]])
    R = np.eye(3) + np.sin(각) * K + (1 - np.cos(각)) * (K @ K)
    return 변환(R, [0.0, 0.0, 0.0])


# 예제용 6자유도 팔. 관절마다 (이름, 앞 관절 기준 고정 위치(m), 회전축)
예제_팔 = [
    ("허리", [0, 0, 0.10], [0, 0, 1]),
    ("어깨", [0, 0, 0.10], [0, 1, 0]),
    ("팔꿈치", [0, 0, 0.30], [0, 1, 0]),
    ("손목1", [0, 0, 0.25], [0, 0, 1]),
    ("손목2", [0, 0, 0.05], [0, 1, 0]),
    ("손목3", [0, 0, 0.05], [0, 0, 1]),
]
손끝_위치 = [0, 0, 0.05]             # 마지막 관절 기준 손끝(도구 끝)


def 순기구학(관절각, 팔=예제_팔, 손끝=손끝_위치) -> list[np.ndarray]:
    """바닥 기준 좌표계 목록: [T_바닥_관절1, ..., T_바닥_관절n, T_바닥_손끝]."""
    T = np.eye(4)
    좌표계들 = []
    for (_, 위치, 축), 각 in zip(팔, 관절각):
        T = T @ 이동(위치) @ 축_회전(축, 각)      # 고정 변환 × 관절 회전
        좌표계들.append(T)
    좌표계들.append(T @ 이동(손끝))
    return 좌표계들
