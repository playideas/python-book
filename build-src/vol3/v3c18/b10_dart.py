import numpy as np

from 모방환경 import 상자_범위
from 시연도구 import 굴리기, 성공률, 시연_모으기, 시험_위치
from 정책도구 import 검증_손실, 학습

깨끗 = 시연_모으기(250)
검증_칸 = 깨끗["에피소드"] >= 200
생성기 = np.random.default_rng(3)
관측들, 행동들 = [], []
for i in range(50):                                     # 전문가도 흔들리는 팔로 시연한다
    o, a, _ = 굴리기(생성기.uniform(*상자_범위), 흔들림=0.004, 씨앗=500 + i)
    관측들.append(o)
    행동들.append(a)
시험 = 시험_위치(50)
for 이름, 관측, 행동 in [("깨끗한 시연 200개", 깨끗["관측"][~검증_칸], 깨끗["행동"][~검증_칸]),
                       ("흔들며 시연 50개 ", np.concatenate(관측들), np.concatenate(행동들))]:
    정책 = 학습(관측, 행동)
    print(f"{이름}: 깨끗한 검증 손실 {검증_손실(정책, 깨끗['관측'][검증_칸], 깨끗['행동'][검증_칸]):.4f}, "
          f"성공률 흔들림 없이 {성공률(정책, 시험):.0%} / 0.004에서 {성공률(정책, 시험, 0.004):.0%}")
