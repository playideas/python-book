import numpy as np

from 시연도구 import 시연_모으기
from 정책도구 import 검증_손실, 학습

데이터 = 시연_모으기(250)
관측, 행동, 에피소드 = 데이터["관측"], 데이터["행동"], 데이터["에피소드"]
쓸_칸 = 에피소드 < 10                                # 앞 10개 에피소드로만 실험한다
새_칸 = 에피소드 >= 200                              # 끝 50개는 진짜 처음 보는 에피소드

생성기 = np.random.default_rng(0)
번호 = np.flatnonzero(쓸_칸)
섞은_검증 = np.zeros(len(관측), bool)
섞은_검증[생성기.choice(번호, len(번호) // 5, replace=False)] = True   # 걸음을 섞어 20%를 검증으로
나누기 = {"걸음 단위로 섞기": (쓸_칸 & ~섞은_검증, 섞은_검증),
         "에피소드 단위로 나누기": (에피소드 < 8, 쓸_칸 & (에피소드 >= 8))}  # 8개 학습, 2개 검증
for 이름, (학습_칸, 검증_칸) in 나누기.items():
    정책 = 학습(관측[학습_칸], 행동[학습_칸], 걸음=20000)
    print(f"{이름:12s}: 학습 {검증_손실(정책, 관측[학습_칸], 행동[학습_칸]):.3f}, "
          f"검증 {검증_손실(정책, 관측[검증_칸], 행동[검증_칸]):.3f}, "
          f"처음 보는 에피소드 {검증_손실(정책, 관측[새_칸], 행동[새_칸]):.3f}")
