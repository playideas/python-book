from 시연도구 import 성공률, 시연_모으기, 시험_위치
from 정책도구 import 검증_손실, 학습

데이터 = 시연_모으기(250)
관측, 행동, 에피소드 = 데이터["관측"], 데이터["행동"], 데이터["에피소드"]
검증_칸, 시험 = 에피소드 >= 200, 시험_위치(50)

print("시연 수  관측 칸  검증 손실  성공률")
for 시연_수, 칸_수 in [(5, 13), (10, 13), (25, 13), (200, 10)]:
    학습_칸 = 에피소드 < 시연_수
    정책 = 학습(관측[학습_칸, :칸_수], 행동[학습_칸])          # 10칸이면 'TCP에서 본 상자'를 뺀다
    print(f"{시연_수:6d}  {칸_수:7d}  {검증_손실(정책, 관측[검증_칸, :칸_수], 행동[검증_칸]):9.4f}  "
          f"{성공률(정책, 시험):6.0%}")
