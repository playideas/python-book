import numpy as np

from 시연도구 import 굴리기, 성공률, 시연_모으기, 시험_위치
from 정책도구 import 학습

데이터 = 시연_모으기(250)
학습_칸 = 데이터["에피소드"] < 200
정책 = 학습(데이터["관측"][학습_칸], 데이터["행동"][학습_칸])
시험 = 시험_위치(50)

print("흔들림(rad)  전문가  BC(시연 200개)")
for 흔들림 in [0.0, 0.002, 0.004, 0.006]:
    전문가_성공 = np.mean([굴리기(p, 흔들림=흔들림, 씨앗=i)[2] for i, p in enumerate(시험)])
    print(f"{흔들림:10.3f}  {전문가_성공:6.0%}  {성공률(정책, 시험, 흔들림):8.0%}")
