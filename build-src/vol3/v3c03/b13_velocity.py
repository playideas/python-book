import numpy as np

from 두링크 import 순기구학2, 야코비안2
from 회전도구 import 깔끔

q = np.deg2rad([30.0, 45.0])
관절_속도 = np.array([0.5, -0.2])               # 어깨 0.5rad/s, 팔꿈치 -0.2rad/s

손끝_속도 = 야코비안2(q) @ 관절_속도             # 속도 기구학: v = J q̇
print("J @ q̇로 구한 손끝 속도 :", 깔끔(손끝_속도, 4), "m/s")

간격 = 0.001                                   # 0.001초 동안 실제로 움직여 보기
움직인_거리 = 순기구학2(q + 관절_속도 * 간격) - 순기구학2(q)
print("실제로 움직여 잰 속도   :", 깔끔(움직인_거리 / 간격, 4), "m/s")

# 첫 열: 어깨만 1rad/s로 돌 때. 손끝은 어깨를 중심으로 원을 그리니 방향은 반지름에 수직
첫_열, 손끝 = 야코비안2(q)[:, 0], 순기구학2(q)
print("첫 열과 손끝 방향의 내적:", round(float(첫_열 @ 손끝), 6) + 0.0)
print("첫 열의 길이:", round(float(np.linalg.norm(첫_열)), 4), "/ 어깨~손끝 거리:", round(float(np.linalg.norm(손끝)), 4))
