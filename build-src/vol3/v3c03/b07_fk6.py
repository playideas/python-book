import numpy as np

from 팔도구 import 순기구학, 예제_팔
from 회전도구 import 깔끔

영점 = np.zeros(6)
T_바닥_손끝 = 순기구학(영점)[-1]
print("모든 관절 0도 → 손끝 위치:", 깔끔(T_바닥_손끝[:3, 3]))

관절각_도 = np.array([30, 45, 60, 0, 45, 0])           # 사람이 읽는 값은 도
좌표계들 = 순기구학(np.deg2rad(관절각_도))
for (이름, _, _), T in zip(예제_팔, 좌표계들):
    print(f"{이름} 관절 위치:", 깔끔(T[:3, 3]))
T_바닥_손끝 = 좌표계들[-1]
print("손끝 위치:", 깔끔(T_바닥_손끝[:3, 3]))
print("손끝 z축(도구가 향한 방향):", 깔끔(T_바닥_손끝[:3, 2]))
