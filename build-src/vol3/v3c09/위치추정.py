"""9.9절 실습: 사진 한 장(컬러+깊이)에서 색깔 물체들의 로봇 기준 위치를 추정한다."""
import numpy as np

from 색찾기 import 물체_찾기

반지름 = {"빨강": 0.035, "초록": 0.03, "파랑": 0.035, "노랑": 0.025}    # 물체 목록에 적어 둔 크기(m)


def 물체_위치_추정(컬러: np.ndarray, 깊이: np.ndarray, K: np.ndarray,
                 T_로봇_카메라: np.ndarray) -> dict[str, np.ndarray]:
    """색으로 찾고 → 깊이로 3차원 → 변환 사슬로 로봇 기준 → 시선 방향으로 반지름만큼 보정."""
    결과 = {}
    for 이름, 물체 in 물체_찾기(컬러).items():
        깊이들 = 깊이[물체["덩어리"]]
        깊이들 = 깊이들[깊이들 > 0]                                  # 값을 못 얻은 픽셀(0)은 뺀다
        if len(깊이들) < 20:
            continue
        u, v = 물체["중심"]
        Z = np.median(깊이들)
        점_카메라 = np.array([(u - K[0, 2]) / K[0, 0] * Z, (v - K[1, 2]) / K[1, 1] * Z, Z, 1.0])
        점_로봇 = (T_로봇_카메라 @ 점_카메라)[:3]
        시선 = 점_로봇 - T_로봇_카메라[:3, 3]
        결과[이름] = 점_로봇 + 반지름[이름] * 시선 / np.linalg.norm(시선)
    return 결과
