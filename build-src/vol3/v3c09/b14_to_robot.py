import mujoco
import numpy as np

from 비전장면 import K_만들기, R_로봇_머리, 머리_fovy, 머리_위치_로봇, 물체들, 변환, 장면_xml, 찍기
from 색찾기 import 물체_찾기
from 회전도구 import 깔끔

모델 = mujoco.MjModel.from_xml_string(장면_xml())
데이터 = mujoco.MjData(모델)
컬러, 깊이 = 찍기(모델, 데이터, "머리")
K = K_만들기(머리_fovy)
T_로봇_카메라 = 변환(R_로봇_머리, 머리_위치_로봇)     # 설계도에 적힌 카메라 설치 위치·자세
T_세계_로봇 = 변환(np.eye(3), [0, 0, 0.75])           # 정답 비교용: 로봇은 탁자 높이에 서 있다

for 이름, 물체 in 물체_찾기(컬러).items():
    u, v = 물체["중심"]
    Z = np.median(깊이[물체["덩어리"]])                       # 덩어리 깊이의 중앙값
    점_카메라 = np.array([(u - K[0, 2]) / K[0, 0] * Z, (v - K[1, 2]) / K[1, 1] * Z, Z, 1.0])
    점_로봇 = (T_로봇_카메라 @ 점_카메라)[:3]                 # 2장의 변환 사슬
    정답_로봇 = (np.linalg.inv(T_세계_로봇) @ [*물체들[이름][0], 1.0])[:3]
    # 보이는 것은 겉면이다: 시선 방향으로 반지름만큼 더 들어가면 중심에 가깝다
    시선 = (점_로봇 - 머리_위치_로봇) / np.linalg.norm(점_로봇 - 머리_위치_로봇)
    보정 = 점_로봇 + 물체들[이름][1] * 시선
    print(f"{이름}: 추정 {깔끔(점_로봇)} 정답 {깔끔(정답_로봇)} 오차 {np.linalg.norm(점_로봇 - 정답_로봇) * 100:4.1f}cm"
          f" → 반지름 보정 뒤 {np.linalg.norm(보정 - 정답_로봇) * 100:4.1f}cm")
