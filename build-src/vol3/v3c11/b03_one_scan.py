import numpy as np

from 방장면 import 라이다_스캔, 레이_각도, 레이_수, 방_만들기

모델, 데이터 = 방_만들기()
포즈 = (2.75, 1.5, 0.0)                      # 섬 아래쪽, 방의 +x를 보고 선 로봇
깨끗 = 라이다_스캔(모델, 데이터, 포즈)
생성기 = np.random.default_rng(0)
잡음섞인 = 라이다_스캔(모델, 데이터, 포즈, 생성기, 잡음=0.02)

print("레이 수:", 레이_수, "/ 간격:", np.rad2deg(레이_각도(레이_수)[1]), "도")
for 도 in [0, 90, 180, 270]:
    k = 도 // 2
    print(f"{도:3d}도 방향: 참 거리 {깨끗[k]:.3f}m, 잰 거리 {잡음섞인[k]:.3f}m")
print("가장 가까운 것:", round(float(np.nanmin(깨끗)), 3), "m /",
      "가장 먼 것:", round(float(np.nanmax(깨끗)), 3), "m")
print("잡음의 표준편차:", round(float(np.std(잡음섞인 - 깨끗)), 4), "m")

# 방 구석(0.5, 7.5)에 서면 8m보다 먼 벽은 돌아오지 않는다
구석 = 라이다_스캔(모델, 데이터, (0.5, 7.5, 0.0))
print("구석에서 돌아오지 않은 레이:", int(np.isnan(구석).sum()), "개")
