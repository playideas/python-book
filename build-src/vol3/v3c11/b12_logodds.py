from 격자도구 import 로그오즈, 빈칸_증거, 찬칸_증거, 확률로

print("확률 0.7의 로그 오즈:", round(float(로그오즈(0.7)), 3), "/ 0.4의 로그 오즈:", round(float(로그오즈(0.4)), 3))
print("확률 0.5(모름)의 로그 오즈:", float(로그오즈(0.5)))

# 한 칸을 여러 번 본 기록: 찬=레이가 거기서 끝남, 빈=레이가 지나감
for 이름, 관측들 in [("벽 칸   ", "찬찬찬찬찬"),
                   ("빈 바닥 ", "빈빈빈빈빈"),
                   ("지나간 사람", "빈빈찬찬빈빈빈")]:
    값 = 0.0
    경과 = []
    for 관측 in 관측들:
        값 += 찬칸_증거 if 관측 == "찬" else 빈칸_증거   # 곱셈 대신 덧셈 한 번
        경과.append(f"{확률로(값):.2f}")
    print(f"{이름}: {' → '.join(경과)}")
