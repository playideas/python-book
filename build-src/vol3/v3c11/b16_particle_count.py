import numpy as np

from 격자도구 import 지도_만들기
from 입자도구 import 다시_뽑기, 벽까지_거리표, 입자_가중치, 입자_뿌리기, 입자_움직이기
from 주행데이터 import 주행_기록

참_포즈들, 바퀴_증분들, 스캔들 = 주행_기록()
지도 = 지도_만들기(참_포즈들, 스캔들)
확률 = 지도.확률()
거리표 = 벽까지_거리표(확률)


def 전역_위치추정(입자_수: int, 씨앗: int) -> float:
    """아무것도 모르는 채 출발해 24걸음 뒤의 추정 오차(m)."""
    생성기 = np.random.default_rng(씨앗)
    입자들 = 입자_뿌리기(입자_수, 확률, 생성기)
    for k in range(25):
        if k > 0:
            입자들 = 입자_움직이기(입자들, 바퀴_증분들[k - 1], 생성기)
        가중치 = 입자_가중치(입자들, 스캔들[k][::12], 거리표)
        추정 = np.average(입자들[:, :2], weights=가중치, axis=0)
        입자들 = 다시_뽑기(입자들, 가중치, 생성기)
    return float(np.linalg.norm(추정 - 참_포즈들[24, :2]))


for 입자_수 in [2000, 5000]:
    오차들 = [전역_위치추정(입자_수, 씨앗) for 씨앗 in range(10)]
    print(f"입자 {입자_수}개, 10번 시도: " + " ".join(f"{e:.2f}" for e in 오차들))
