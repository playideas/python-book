"""11장: 가운데 섬을 한 바퀴 도는 주행 기록(참 포즈, 바퀴 오도메트리, 라이다 스캔)을 만든다."""
import numpy as np

from 방장면 import 라이다_스캔, 레이_수, 방_만들기, 스캔_점들
from 포즈도구 import 포즈_잇기

시작_포즈 = np.array([2.75, 1.5, 0.0])     # 섬 아래쪽에서 +x를 보고 출발
걸음 = 0.25                               # m. 곧은 길에서 한 번에 가는 거리
회전_반지름 = 1.0                         # m. 모퉁이는 반지름 1m 호로 돈다
스캔_잡음 = 0.02                          # m. 라이다 거리 잡음
바퀴_잡음 = (0.01, 0.004)                 # 한 걸음마다 거리(m), 방향(rad) 잡음
바퀴_치우침 = 0.004                       # rad. 한 걸음마다 늘 왼쪽으로 더 돌았다고 센다


def 참_증분들() -> np.ndarray:
    """곧게 4.5m → 왼쪽 90도 호 → 곧게 3m → 호 … 로 한 바퀴. 로봇 기준 (앞, 왼쪽, 회전) 84개."""
    호_한걸음 = np.pi / 12                                 # 호 하나를 15도씩 6걸음에
    호 = [(2 * 회전_반지름 * np.sin(호_한걸음 / 2), 0.0, 호_한걸음)] * 6
    아래 = [(걸음, 0.0, 0.0)] * 18
    옆 = [(걸음, 0.0, 0.0)] * 12
    증분들 = []
    for 곧은길 in [아래, 옆, 아래, 옆]:
        증분들 += 곧은길 + 호
    # 호의 현을 따라 간 뒤 돌면 다음 방향이 맞도록, 회전 절반을 앞뒤로 나눠 준다
    return np.array([[d * np.cos(a / 2), d * np.sin(a / 2), a] for d, _, a in 증분들])


def 주행_기록(씨앗: int = 0, 레이_개수: int = 레이_수):
    """(참 포즈들 N×3, 바퀴 증분들 (N-1)×3, 로봇 기준 스캔 점구름 N개)를 돌려준다."""
    생성기 = np.random.default_rng(씨앗)
    모델, 데이터 = 방_만들기()
    참_포즈들 = [시작_포즈]
    for 증분 in 참_증분들():
        참_포즈들.append(포즈_잇기(참_포즈들[-1], 증분))
    참_포즈들 = np.array(참_포즈들)

    바퀴_증분들 = []
    for 앞, 왼쪽, 회전 in 참_증분들():
        잰_거리 = np.hypot(앞, 왼쪽) + 생성기.normal(0, 바퀴_잡음[0])
        잰_회전 = 회전 + 바퀴_치우침 + 생성기.normal(0, 바퀴_잡음[1])
        바퀴_증분들.append([잰_거리 * np.cos(잰_회전 / 2), 잰_거리 * np.sin(잰_회전 / 2), 잰_회전])

    스캔들 = [스캔_점들(라이다_스캔(모델, 데이터, 포즈, 생성기, 스캔_잡음, 레이_개수)) for 포즈 in 참_포즈들]
    return 참_포즈들, np.array(바퀴_증분들), 스캔들
