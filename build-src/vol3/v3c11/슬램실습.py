"""11장 실습: 스캔 정합 오도메트리로 포즈 그래프의 간선을 만들고, 루프를 찾는다."""
import numpy as np

from 정합도구 import icp
from 포즈도구 import 상대_포즈, 포즈_잇기, 포즈_행렬, 행렬_포즈

루프_반경 = 1.0          # m. 추정 위치가 이만큼 가까우면 같은 곳에 왔을지 모른다
루프_간격 = 20           # 걸음. 바로 앞뒤 스캔은 루프가 아니다
정합_합격선 = 0.12       # m. ICP가 끝난 뒤 짝 사이 평균 거리가 이보다 작아야 믿는다


def 정합_오도메트리(스캔들: list, 바퀴_증분들: np.ndarray, 시작_포즈: np.ndarray):
    """이웃 스캔을 ICP로 맞춰 포즈를 이어 붙이고, 그 상대 포즈를 간선으로 남긴다."""
    포즈들 = [시작_포즈]
    간선들 = []
    for k, 증분 in enumerate(바퀴_증분들):
        T_이전_지금, _ = icp(스캔들[k + 1], 스캔들[k], 포즈_행렬(증분))
        상대 = 행렬_포즈(T_이전_지금)
        간선들.append((k, k + 1, 상대))
        포즈들.append(포즈_잇기(포즈들[-1], 상대))
    return np.array(포즈들), 간선들


def 루프_찾기(포즈들: np.ndarray, 스캔들: list) -> list:
    """멀리 돌아 가까운 곳에 다시 온 스캔 쌍을 ICP로 확인해 루프 간선을 만든다."""
    간선들 = []
    for 지금 in range(len(포즈들)):
        후보 = np.arange(0, 지금 - 루프_간격)
        if len(후보) == 0:
            continue
        거리 = np.linalg.norm(포즈들[후보, :2] - 포즈들[지금, :2], axis=1)
        if 거리.min() > 루프_반경:
            continue
        예전 = int(후보[거리.argmin()])
        추측 = 포즈_행렬(상대_포즈(포즈들[예전], 포즈들[지금]))    # 지금까지 쌓인 포즈로 한 추측
        T_예전_지금, 기록 = icp(스캔들[지금], 스캔들[예전], 추측)
        if 기록[-1] < 정합_합격선:
            간선들.append((예전, 지금, 행렬_포즈(T_예전_지금)))
    return 간선들
