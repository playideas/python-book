import numpy as np

from 슬램실습 import 루프_찾기, 정합_오도메트리
from 주행데이터 import 주행_기록
from 포즈그래프 import 그래프_펴기
from 포즈도구 import 각도_정리, 상대_포즈

참_포즈들, 바퀴_증분들, 스캔들 = 주행_기록(레이_개수=90)   # 4도 간격의 값싼 라이다
정합_포즈들, 이웃_간선들 = 정합_오도메트리(스캔들, 바퀴_증분들, 참_포즈들[0])
루프_간선들 = 루프_찾기(정합_포즈들, 스캔들)
print("정합 오도메트리로 본 84번 포즈(0번 기준):", np.round(상대_포즈(정합_포즈들[0], 정합_포즈들[84]), 3) + 0.0)
print("이웃 간선", len(이웃_간선들), "개, 루프 간선", len(루프_간선들), "개")
for 예전, 지금, 잰_값 in 루프_간선들:
    정답 = 상대_포즈(참_포즈들[예전], 참_포즈들[지금])
    print(f"  {지금}번 → {예전}번: ICP {np.round(잰_값[:2], 2) + 0.0}, 정답 {np.round(정답[:2], 2) + 0.0}")
펴진_포즈들 = 그래프_펴기(정합_포즈들, 이웃_간선들 + 루프_간선들)

# 일부러 틀린 루프 하나: 섬 건너편 42번 자리를 0번 자리라고 우긴다
거짓_간선 = (0, 42, np.zeros(3))
망친_포즈들 = 그래프_펴기(정합_포즈들, 이웃_간선들 + 루프_간선들 + [거짓_간선])


def 보고(이름: str, 포즈들: np.ndarray) -> None:
    위치 = np.linalg.norm(포즈들[:, :2] - 참_포즈들[:, :2], axis=1)
    방향 = np.rad2deg(np.abs(각도_정리(포즈들[:, 2] - 참_포즈들[:, 2])))
    print(f"{이름:14s}: 위치 오차 평균 {위치.mean():.3f}m, 가장 큰 {위치.max():.3f}m, 방향 오차 가장 큰 {방향.max():.2f}도")


보고("정합 오도메트리", 정합_포즈들)
보고("루프 닫기 후", 펴진_포즈들)
보고("거짓 루프 섞임", 망친_포즈들)
