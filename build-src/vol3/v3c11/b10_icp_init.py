import numpy as np

from 정합도구 import icp
from 주행데이터 import 주행_기록
from 포즈도구 import 각도_정리, 상대_포즈, 포즈_행렬, 행렬_포즈

참_포즈들, 바퀴_증분들, 스캔들 = 주행_기록()


def 오차(T: np.ndarray, 정답: np.ndarray) -> tuple[float, float]:
    차이 = 행렬_포즈(T) - 정답
    return float(np.hypot(차이[0], 차이[1])), float(np.rad2deg(abs(각도_정리(차이[2]))))


print("[처음 추측을 '안 움직였다'로 둘 때, 두 스캔 사이가 멀어지면]")
for k in [1, 2, 4, 6, 8]:
    정답 = 상대_포즈(참_포즈들[0], 참_포즈들[k])
    위치, 각 = 오차(icp(스캔들[k], 스캔들[0])[0], 정답)
    print(f"  {정답[0]:.2f}m 떨어짐: 위치 오차 {위치:.3f}m, 각 오차 {각:5.2f}도")

print("[두 스캔은 0.5m 떨어져 있고, 처음 추측의 방향만 틀릴 때]")
정답 = 상대_포즈(참_포즈들[0], 참_포즈들[2])
for 틀린_도 in [0, 15, 30, 45, 60, 90]:
    추측 = 포즈_행렬(정답 + [0, 0, np.deg2rad(틀린_도)])
    위치, 각 = 오차(icp(스캔들[2], 스캔들[0], 추측)[0], 정답)
    print(f"  방향 {틀린_도:2d}도 틀린 추측: 위치 오차 {위치:.3f}m, 각 오차 {각:5.2f}도")
