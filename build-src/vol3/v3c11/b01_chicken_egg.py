import numpy as np

거리 = 2.0          # 라이다가 로봇 앞쪽으로 잰 벽까지의 거리(m)

# 1) 위치를 알면 지도를 그린다: 내 포즈에서 2m 앞에 벽이 있다
for 이름, (x, y, 각_도) in [("맞는 포즈     ", (1.0, 1.0, 0)),
                          ("방향이 5도 틀림", (1.0, 1.0, 5)),
                          ("위치가 0.3m 틀림", (1.3, 1.0, 0))]:
    각 = np.deg2rad(각_도)
    벽_방 = np.array([x + 거리 * np.cos(각), y + 거리 * np.sin(각)])
    print(f"{이름}: 벽을 {np.round(벽_방, 3)}에 그린다")

# 2) 지도를 알면 위치를 안다: 벽이 x = 3m에 있다고 지도에 적혀 있다면
벽_x = 3.0
print("지도로 거꾸로 찾은 로봇의 x:", 벽_x - 거리)
