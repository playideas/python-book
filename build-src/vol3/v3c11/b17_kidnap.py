import numpy as np

from 격자도구 import 지도_만들기
from 입자도구 import 다시_뽑기, 벽까지_거리표, 입자_가중치, 입자_뿌리기, 입자_움직이기
from 주행데이터 import 주행_기록

참_포즈들, 바퀴_증분들, 스캔들 = 주행_기록()
지도 = 지도_만들기(참_포즈들, 스캔들)
확률 = 지도.확률()
거리표 = 벽까지_거리표(확률)

# 0~29번 자리를 지나다가, 누가 로봇을 번쩍 들어 60번 자리에 내려놓는다
순서 = list(range(0, 30)) + list(range(60, 85))
납치_걸음 = 30


def 따라가기(새_입자_비율: float, 씨앗: int) -> list[float]:
    생성기 = np.random.default_rng(씨앗)
    # 이번에는 출발 위치를 알고 시작한다: 시작 포즈 둘레에 입자를 모아 둔다
    입자들 = 참_포즈들[0] + 생성기.normal(0, [0.1, 0.1, 0.05], size=(2000, 3))
    오차들 = []
    for 걸음, k in enumerate(순서):
        if 걸음 > 0:
            # 바퀴는 들려 간 줄 모르니, 납치된 걸음에도 평소처럼 한 걸음 증분을 알려 준다
            증분 = 바퀴_증분들[0] if 걸음 == 납치_걸음 else 바퀴_증분들[k - 1]
            입자들 = 입자_움직이기(입자들, 증분, 생성기)
        가중치 = 입자_가중치(입자들, 스캔들[k][::12], 거리표)
        추정 = np.average(입자들[:, :2], weights=가중치, axis=0)
        오차들.append(float(np.linalg.norm(추정 - 참_포즈들[k, :2])))
        입자들 = 다시_뽑기(입자들, 가중치, 생성기)
        # 일부 입자를 지도 전체에 새로 뿌려 '혹시 다른 곳은 아닐까'를 늘 열어 둔다
        새로 = int(새_입자_비율 * len(입자들))
        if 새로 > 0:
            입자들[:새로] = 입자_뿌리기(새로, 확률, 생성기)
    return 오차들


for 비율 in [0.0, 0.02, 0.05]:
    오차들 = np.array([따라가기(비율, 씨앗) for 씨앗 in range(10)])     # 10번 시도 × 걸음
    print(f"새 입자 {비율:.0%}: 납치 직전 오차 평균 {오차들[:, 납치_걸음 - 1].mean():.2f}m, "
          f"되찾음(0.3m 안) {(오차들[:, -1] < 0.3).sum()}번, 5m 넘게 틀림 {(오차들[:, -1] > 5).sum()}번")
