import numpy as np

from 골격도구 import 번호
from 두링크 import 팔_점들
from 따라하기 import 배율, 사람_팔_각, 손끝_매핑, 평면_좌표
from 사람모델 import 키포인트_3d

도 = np.deg2rad
print(f"로봇 팔 0.7m ÷ 사람 팔 0.57m = 배율 {배율:.3f}")
for 팔꿈치_도 in [25, 60, 95]:
    점들 = 키포인트_3d(오른팔_각=[도(120), 0, 도(-90), 도(팔꿈치_도)])
    어깨, 팔꿈치, 손목 = (점들[번호[이름]] for 이름 in ["오른어깨", "오른팔꿈치", "오른손목"])
    관절_매핑 = 사람_팔_각(어깨, 팔꿈치, 손목)
    손끝 = 손끝_매핑(어깨, 손목, 관절_매핑)
    목표 = 평면_좌표(손목, 어깨) * 배율
    print(f"사람 팔꿈치 {팔꿈치_도}도, 손 목표 {np.round(목표, 3)}")
    for 이름, q in [("관절 매핑", 관절_매핑), ("손끝 매핑", 손끝)]:
        로봇_손 = 팔_점들(q)[2]
        print(f"   {이름}: 관절 {np.rad2deg(q).round(1) + 0.0}도 → 로봇 손 {np.round(로봇_손, 3) + 0.0}, "
              f"목표와 {np.linalg.norm(로봇_손 - 목표) * 1000:4.1f}mm")
