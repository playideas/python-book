import numpy as np

from 사람모델 import 팔_점들

도 = np.deg2rad
자세들 = {"차렷": [0, 0, 0, 0],
        "팔꿈치만 90도": [0, 0, 0, 도(90)],
        "옆으로 90도 들기": [도(90), 0, 0, 0],
        "앞으로 90도 들기": [0, 도(90), 0, 0],
        "손 흔들기 자세": [도(120), 0, 도(-90), 도(60)]}
print("오른팔 [옆들기, 앞들기, 비틀기, 팔꿈치](도) → 어깨 기준 손목 위치(m)")
for 이름, 각 in 자세들.items():
    _, 손목 = 팔_점들(-1, 각)
    print(f"  {str(np.rad2deg(각).round().astype(int)):16s} → {np.round(손목, 3) + 0.0}  {이름}")

# 팔을 옆으로 든 채 팔꿈치를 90도 굽힐 때, 위팔을 비튼 정도에 따라 손목이 가는 곳
for 비틀기 in [-90, 0, 90]:
    팔꿈치, 손목 = 팔_점들(-1, [도(90), 0, 도(비틀기), 도(90)])
    print(f"비틀기 {비틀기:3d}도 → 팔꿈치 {np.round(팔꿈치, 3) + 0.0}, 손목 {np.round(손목, 3) + 0.0}")
