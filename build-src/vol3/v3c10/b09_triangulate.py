import numpy as np

from 카메라도구 import 삼각측량, 카메라_만들기, 투영

# 사람 앞 3m 떨어진 곳에 카메라 두 대를 좌우로 2.4m 벌려 세우고 가슴 높이를 보게 한다
P왼 = 카메라_만들기([3.0, 1.2, 1.3], [0, 0, 1.2])
P오 = 카메라_만들기([3.0, -1.2, 1.3], [0, 0, 1.2])
손목_세계 = np.array([0.0, -0.44, 1.87])                  # 손 흔들기 자세의 오른손목(10.1절)

픽셀왼, 픽셀오 = 투영(P왼, 손목_세계[None])[0], 투영(P오, 손목_세계[None])[0]
print("왼쪽 카메라 픽셀:", np.round(픽셀왼, 1), "/ 오른쪽 카메라 픽셀:", np.round(픽셀오, 1))
복원 = 삼각측량([P왼, P오], [픽셀왼, 픽셀오])
print("잡음 없이 복원:", np.round(복원, 4) + 0.0, "/ 오차", f"{np.linalg.norm(복원 - 손목_세계) * 1000:.4f}mm")

# 픽셀에 잡음을 넣고 1000번 되풀이해 오차를 잰다
생성기 = np.random.default_rng(0)
for 잡음_px in [0.5, 1, 2, 5]:
    오차_mm = []
    for _ in range(1000):
        흔들린 = [픽셀왼 + 생성기.normal(0, 잡음_px, 2), 픽셀오 + 생성기.normal(0, 잡음_px, 2)]
        오차_mm.append(np.linalg.norm(삼각측량([P왼, P오], 흔들린) - 손목_세계) * 1000)
    print(f"픽셀 잡음 {잡음_px:3}px → 3D 오차 평균 {np.mean(오차_mm):5.1f}mm, 95% {np.percentile(오차_mm, 95):5.1f}mm")
