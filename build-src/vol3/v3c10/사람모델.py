"""10장: 서 있는 사람의 3D 키포인트를 순기구학으로 만드는 예제용 모델(단위 m, rad).

사람은 원점에 서서 +x 쪽을 본다(몸 좌표: x 앞, y 왼쪽, z 위).
"""
import numpy as np

from 골격도구 import 번호
from 팔도구 import 순기구학

위팔_길이, 아래팔_길이 = 0.30, 0.27          # 어깨~팔꿈치, 팔꿈치~손목(m)

# 몸통과 머리의 고정된 점들. 오른쪽은 y가 음수다
고정점 = {"코": [0.10, 0.0, 1.62], "왼눈": [0.08, 0.035, 1.66], "오른눈": [0.08, -0.035, 1.66],
        "왼귀": [0.0, 0.075, 1.63], "오른귀": [0.0, -0.075, 1.63],
        "왼어깨": [0.0, 0.18, 1.45], "오른어깨": [0.0, -0.18, 1.45],
        "왼엉덩이": [0.0, 0.10, 0.95], "오른엉덩이": [0.0, -0.10, 0.95],
        "왼무릎": [0.02, 0.10, 0.52], "오른무릎": [0.02, -0.10, 0.52],
        "왼발목": [0.0, 0.10, 0.08], "오른발목": [0.0, -0.10, 0.08]}


def 사람_팔(쪽: int) -> list:
    """3장 팔도구.py 형식의 팔 사슬. 쪽 = +1이면 왼팔, -1이면 오른팔."""
    return [("어깨_옆들기", [0, 0, 0], [쪽, 0, 0]),       # 팔을 옆으로 벌리기
            ("어깨_앞들기", [0, 0, 0], [0, -1, 0]),       # 팔을 앞으로 들기
            ("어깨_비틀기", [0, 0, 0], [0, 0, 1]),        # 위팔을 길이 방향 축으로 비틀기
            ("팔꿈치", [0, 0, -위팔_길이], [0, -1, 0])]    # 팔꿈치 굽히기(앞쪽으로)


def 팔_점들(쪽: int, 관절각) -> tuple[np.ndarray, np.ndarray]:
    """어깨 기준 팔꿈치·손목 위치. 관절각 = [옆들기, 앞들기, 비틀기, 팔꿈치](rad)."""
    좌표계들 = 순기구학(관절각, 팔=사람_팔(쪽), 손끝=[0, 0, -아래팔_길이])
    return 좌표계들[3][:3, 3], 좌표계들[4][:3, 3]


def 키포인트_3d(오른팔_각=(0, 0, 0, 0), 왼팔_각=(0, 0, 0, 0)) -> np.ndarray:
    """COCO 순서의 17×3 키포인트(세계 좌표, m)."""
    점들 = np.zeros((17, 3))
    for 이름, 위치 in 고정점.items():
        점들[번호[이름]] = 위치
    for 쪽, 이름, 각 in [(-1, "오른", 오른팔_각), (+1, "왼", 왼팔_각)]:
        어깨 = 점들[번호[이름 + "어깨"]]
        팔꿈치, 손목 = 팔_점들(쪽, 각)
        점들[번호[이름 + "팔꿈치"]] = 어깨 + 팔꿈치
        점들[번호[이름 + "손목"]] = 어깨 + 손목
    return 점들
