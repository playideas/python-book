import numpy as np

from 골격도구 import 번호
from 사람모델 import 키포인트_3d
from 카메라도구 import 카메라_만들기, 투영


def 사이각_도(가: np.ndarray, 중심: np.ndarray, 나: np.ndarray) -> float:
    """중심에서 가와 나를 향한 두 벡터 사이의 각도(도). 2D든 3D든 같은 식이다."""
    u, v = 가 - 중심, 나 - 중심
    코사인 = u @ v / (np.linalg.norm(u) * np.linalg.norm(v))
    return float(np.rad2deg(np.arccos(np.clip(코사인, -1, 1))))


도 = np.deg2rad
자세들 = {"손 흔들기(팔꿈치 60도)": [도(120), 0, 도(-90), 도(60)],
        "팔을 앞으로 뻗고 팔꿈치 90도": [도(10), 도(70), 0, 도(90)]}
카메라들 = {"정면": [3.0, 0.0, 1.3], "오른쪽 45도": [2.1, -2.1, 1.3], "위": [0.3, 0.0, 4.0]}
for 이름, 각 in 자세들.items():
    점들 = 키포인트_3d(오른팔_각=각)
    세_점 = [번호["오른어깨"], 번호["오른팔꿈치"], 번호["오른손목"]]
    참 = 사이각_도(*점들[세_점])
    줄 = [f"3D {참:5.1f}도"]
    for 카메라_이름, 위치 in 카메라들.items():
        픽셀 = 투영(카메라_만들기(위치, [0, 0, 1.3]), 점들[세_점])
        줄.append(f"{카메라_이름} {사이각_도(*픽셀):5.1f}도")
    print(f"{이름}\n   " + " / ".join(줄))
