"""10장: COCO 17 키포인트 골격의 이름, 뼈 연결, 그리기 도구."""
import numpy as np

# COCO 데이터셋의 키포인트 17개. 순서가 곧 번호다(모델 출력의 줄 순서와 같다)
키포인트_이름 = ["코", "왼눈", "오른눈", "왼귀", "오른귀",
              "왼어깨", "오른어깨", "왼팔꿈치", "오른팔꿈치", "왼손목", "오른손목",
              "왼엉덩이", "오른엉덩이", "왼무릎", "오른무릎", "왼발목", "오른발목"]
번호 = {이름: i for i, 이름 in enumerate(키포인트_이름)}

# 어느 키포인트끼리 선으로 이을지(뼈). 링크에 해당한다
뼈 = [("코", "왼눈"), ("코", "오른눈"), ("왼눈", "왼귀"), ("오른눈", "오른귀"),
     ("왼어깨", "오른어깨"), ("왼엉덩이", "오른엉덩이"),
     ("왼어깨", "왼엉덩이"), ("오른어깨", "오른엉덩이"),
     ("왼어깨", "왼팔꿈치"), ("왼팔꿈치", "왼손목"),
     ("오른어깨", "오른팔꿈치"), ("오른팔꿈치", "오른손목"),
     ("왼엉덩이", "왼무릎"), ("왼무릎", "왼발목"),
     ("오른엉덩이", "오른무릎"), ("오른무릎", "오른발목")]


def 뼈_색(가: str, 나: str) -> str:
    """사람의 왼쪽은 파랑, 오른쪽은 주황, 가운데는 회색으로 칠한다."""
    if 가.startswith("왼") and 나.startswith("왼"):
        return "tab:blue"
    if 가.startswith("오른") and 나.startswith("오른"):
        return "tab:orange"
    return "gray"


def 골격_그리기(칸, 점들: np.ndarray, 보임=None, 굵기: float = 2.5) -> None:
    """2D 키포인트(17×2)를 뼈로 이어 그린다. 보임[i]가 False인 점과 그 뼈는 건너뛴다."""
    보임 = np.ones(len(점들), bool) if 보임 is None else np.asarray(보임)
    for 가, 나 in 뼈:
        i, j = 번호[가], 번호[나]
        if 보임[i] and 보임[j]:
            칸.plot(점들[[i, j], 0], 점들[[i, j], 1], color=뼈_색(가, 나), linewidth=굵기)
    칸.scatter(점들[보임, 0], 점들[보임, 1], s=12, color="white", edgecolors="black", zorder=3)
