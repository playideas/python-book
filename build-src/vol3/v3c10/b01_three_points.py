import numpy as np

# 사진 속 한 사람의 왼팔 키포인트 세 개(픽셀 좌표). 10.2절에서 모델이 찾아 준 값이다
어깨 = np.array([528.0, 285.0])
팔꿈치 = np.array([571.0, 357.0])
손목 = np.array([585.0, 450.0])

위팔 = 어깨 - 팔꿈치                     # 팔꿈치에서 어깨로 가는 벡터
아래팔 = 손목 - 팔꿈치                   # 팔꿈치에서 손목으로 가는 벡터
코사인 = 위팔 @ 아래팔 / (np.linalg.norm(위팔) * np.linalg.norm(아래팔))
사이각_도 = np.rad2deg(np.arccos(코사인))
print(f"팔꿈치 사이각: {사이각_도:.1f}도 (180도면 쭉 편 팔)")
print(f"굽힌 정도: {180 - 사이각_도:.1f}도")
